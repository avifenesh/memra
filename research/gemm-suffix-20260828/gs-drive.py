FILLER = ("alpha beta gamma delta epsilon zeta eta theta iota kappa lambda mu nu xi omicron "
          "pi rho sigma tau upsilon phi chi psi omega ").split()

def filler(nwords):
    if nwords <= 0: return ""
    reps = nwords // len(FILLER) + 1
    return " " + " ".join((FILLER * reps)[:nwords])

def turn1(nonce=""):
    return [{"role": "user", "content": nonce + U1}]

def turn2(asst, nwords, nonce=""):
    return turn1(nonce) + [
        {"role": "assistant", "content": asst},
        {"role": "user", "content": "Expand the second point and explain the trade-offs."
                                    + filler(nwords)}]

FIRST_KEYS = []
def stream_once(msgs, sid, maxtok=None):
    payload = {"model": "step37", "messages": msgs, "stream": True,
               "max_tokens": maxtok or MAXTOK, "temperature": 0}
    if sid: payload["session_id"] = sid
    req = urllib.request.Request(URL, data=json.dumps(payload).encode(),
                                 headers={"Content-Type": "application/json"})
    t0 = time.perf_counter(); ttft = None; parts = []
    try:
        r = urllib.request.urlopen(req, timeout=1800)
    except urllib.error.HTTPError as e:
        return (None, time.perf_counter() - t0, "", e.read().decode("utf-8", "replace")[:300])
    for raw in r:
        line = raw.decode("utf-8", "replace").strip()
        if not line.startswith("data:"): continue
        s = line[5:].strip()
        if s == "[DONE]": break
        try: ch = json.loads(s)
        except Exception: continue
        d = ch.get("choices", [{}])[0].get("delta", {}) or {}
        if d and not FIRST_KEYS: FIRST_KEYS.append(sorted(d.keys()))
        piece = (d.get("reasoning") or "") + (d.get("content") or "")
        if piece:
            if ttft is None: ttft = time.perf_counter() - t0
            parts.append(piece)
    return (ttft, time.perf_counter() - t0, "".join(parts), None)

PROBE = [0]
def prompt_tokens(msgs):
    """Exact prompt length read off the ENGINE's own prime receipt: every [gemm-prime] line
    carries seq_end = the request's absolute end position, which for a fresh prime IS the
    prompt token count. Measured, not estimated, and it does not depend on a usage block."""
    PROBE[0] += 1
    pos = logf.tell()
    stream_once(msgs, "gsPROBE-%s-%d" % (name, PROBE[0]), maxtok=1)
    logf.seek(pos); sl = logf.read(); logf.seek(0, 2)
    ends = []
    for l in sl.splitlines():
        if "[gemm-prime]" in l:
            for tok in l.split():
                if tok.startswith("seq_end="):
                    ends.append(int(tok[8:]))
    return max(ends) if ends else None

logf = open(logp, "r", errors="replace"); logf.seek(0, 2)
rows = []

def send(tag, key, msgs, sid):
    pos = logf.tell()
    ttft, total, text, err = stream_once(msgs, sid)
    logf.seek(pos); sl = logf.read(); logf.seek(0, 2)
    rewound = "plain-affinity: rewound to" in sl
    refused = ("plain-affinity resume failed" in sl) or ("affinity rewind failed" in sl)
    eng = [l for l in sl.splitlines() if "[gemm-prime] ENGAGED" in l]
    walk = [l for l in sl.splitlines() if "[gemm-prime] WALK" in l]
    def bases(lines):
        out = []
        for l in lines:
            for tok in l.split():
                if tok.startswith("base="):
                    out.append(int(tok[5:]))
        return out
    eb, wb = bases(eng), bases(walk)
    suffix_tokens = None
    for l in sl.splitlines():
        if "plain-affinity: rewound to" in l:
            p = l.split("(priming ")
            if len(p) > 1: suffix_tokens = int(p[1].split()[0])
    sha = hashlib.sha256(text.encode()).hexdigest()[:16] if text.strip() else None
    r = dict(tag=tag, key=key, ttft=ttft, total=total, chars=len(text), sha=sha,
             rewound=rewound, refused=refused, err=err, suffix=suffix_tokens,
             eng_fresh=sum(1 for b in eb if b == 0), eng_suffix=sum(1 for b in eb if b > 0),
             walk_fresh=sum(1 for b in wb if b == 0), walk_suffix=sum(1 for b in wb if b > 0))
    rows.append(r)
    print("    %-10s %-14s ttft=%s chars=%d sha=%s rewound=%s suffix=%s "
          "eng[fresh=%d suffix=%d] walk[fresh=%d suffix=%d]%s"
          % (tag, key, ("%.3f" % ttft) if ttft is not None else "NONE", len(text),
             sha or "EMPTY", rewound, suffix_tokens, r["eng_fresh"], r["eng_suffix"],
             r["walk_fresh"], r["walk_suffix"], (" err=%s" % err) if err else ""))
    for l in (eng + walk)[:2]:
        print("        %s" % l.strip()[:150])
    return r

