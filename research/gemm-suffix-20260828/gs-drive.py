# lane/gemm-suffix driver.
#
# The question: can a CONTINUATION (suffix) prime ride the batched GEMM path, and does it stay
# the SAME numeric program as a cold full prime of the same bytes?
#
# LEG S -- SUFFIX BYTE IDENTITY, swept over suffix length. For each target suffix length L:
#   (1) establish a session with turn 1 (parks a cache),
#   (2) send turn 2 on the SAME session_id -> the worker rewinds and primes an L-token suffix,
#   (3) send the SAME BYTES on a FRESH session_id -> a cold full prime of the identical prompt.
# Greedy, so (2) and (3) must agree byte for byte. The sweep BRACKETS the 512-row SWA window
# (below it is where the chunk-local seq_end dropped the window mask) and reaches past the
# 4096-token chunk width, so a suffix that itself chunks into 4096 + short-tail is covered.
#
# LEG G -- TTFT on a GROWING conversation, 5 interleaved cold/warm pairs (the shape the affinity
# lane measured at ratio 1.012x). Pre-baked assistant text: both arms prime identical bytes.
#
# LEG F -- one FRESH prompt sized to 4096 + k, k in [16, 512): the shape in which the chunk-local
# seq_end was already wrong before any continuation existed. Its sha is reported for cross-arm
# comparison (default vs the MEMRA_STEP35_PRIME_BATCH_TSEND canary).
#
# INSTRUMENT RULES paid for in this lane:
#  * every generated byte of a thinking model is in `reasoning`; hash reasoning + content.
#  * sha256("") is a constant, so two empty completions compare EQUAL -> empties are rejected
#    HERE, and a row with no ttft or an HTTP error is not a row.
#  * a cold row that REWOUND is not a cold row; it is reported INVALID rather than compared.
