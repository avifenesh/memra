# SUFFIX COST LINE, this arm. The coordinator's five-point sweep measured the WALK suffix at
# ttft = 0.2529 s + 5.5978 ms/suffix-token (R^2 0.9976) against a cold chunked prime of
# 0.99 ms/token. The whole claim of this lane is that the slope collapses to the cold rate
# when the suffix rides the batched entry, so fit the same line here, per arm, from LEG S's
# own warm rows -- same instrument, same cell, directly comparable slopes.
def lsq(xs, ys):
    n = len(xs)
    if n < 3: return None
    mx = sum(xs) / n; my = sum(ys) / n
    sxx = sum((x - mx) ** 2 for x in xs)
    if sxx == 0: return None
    b = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sxx
    a = my - b * mx
    ss_res = sum((y - (a + b * x)) ** 2 for x, y in zip(xs, ys))
    ss_tot = sum((y - my) ** 2 for y in ys)
    r2 = 1 - ss_res / ss_tot if ss_tot > 0 else float("nan")
    return a, b, r2

