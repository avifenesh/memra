def words_for(target_suffix, asst):
    """filler words so the SUFFIX (assistant text + follow-up user turn) is ~target tokens."""
    if not tpw: return max(0, int(target_suffix * 0.75))
    fixed = len(asst.split()) * 1.35 + 25          # assistant text + chat-template markers
    return max(0, int(round((target_suffix - fixed) / tpw)))

