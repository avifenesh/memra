def stats(v):
    if not v: return "n=0"
    s = sorted(v); m = s[len(s)//2] if len(s) % 2 else (s[len(s)//2-1]+s[len(s)//2])/2
    return "n=%d median=%.3f min=%.3f max=%.3f spread=%.3f" % (len(s), m, s[0], s[-1], s[-1]-s[0])

