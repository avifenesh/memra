#!/usr/bin/env python3
"""Compress a DeepSeek-V4.1 header census into the checked-in class fixture, losslessly.

Input: census.json, {name: [shard, dtype, shape, nbytes]} read from the 48 safetensors headers
of deepseek-ai/DeepSeek-V4.1-Flash-1017@1bae0e1088993b9b82de08f59de5be5a34e42170 by HTTP range
requests (no weights downloaded). Output: one row per (name pattern, dtype, shape) with the layer
or block indices it covers and the expert count, the format the deepseek_v41 pack test expands.
The script expands its own output and refuses to write unless the expansion reproduces every
name, dtype and shape of the input.

Usage: census_classes.py CENSUS_JSON OUT_TSV
"""
import json
import re
import sys
from collections import defaultdict

REPO = "deepseek-ai/DeepSeek-V4.1-Flash-1017"
REV = "1bae0e1088993b9b82de08f59de5be5a34e42170"
NAME = re.compile(r"^(layers|mtp|vision\.blocks)\.(\d+)\.(.*)$")
EXPERT = re.compile(r"^(.*\.experts\.)(\d+)(\..*)$")


def ranges(values):
    values = sorted(values)
    out, start = [], values[0]
    for prev, cur in zip(values, values[1:] + [None]):
        if cur != prev + 1:
            out.append(str(start) if start == prev else f"{start}-{prev}")
            start = cur
    return ",".join(out)


def parse_ranges(text):
    out = []
    for part in text.split(","):
        a, _, b = part.partition("-")
        out.extend(range(int(a), int(b or a) + 1))
    return out


def expand(rows):
    names = {}
    for pattern, dtype, shape, indices, experts in rows:
        layers = parse_ranges(indices) if indices != "-" else [None]
        count = int(experts) if experts != "-" else None
        for layer in layers:
            name = pattern if layer is None else pattern.replace("{L}", str(layer))
            for expert in range(count) if count is not None else [None]:
                full = name if expert is None else name.replace("{E}", str(expert))
                assert full not in names, full
                names[full] = (dtype, shape)
    return names


def main(census_path, out_path):
    census = json.load(open(census_path))
    # (pattern, dtype, shape) -> {layer: set(experts)}
    groups = defaultdict(lambda: defaultdict(set))
    for name, (_shard, dtype, shape, _nbytes) in census.items():
        layer, pattern = None, name
        m = NAME.match(name)
        if m:
            layer, pattern = int(m.group(2)), f"{m.group(1)}.{{L}}.{m.group(3)}"
        expert = None
        e = EXPERT.match(pattern)
        if e:
            expert, pattern = int(e.group(2)), f"{e.group(1)}{{E}}{e.group(3)}"
        groups[(pattern, dtype, ",".join(map(str, shape)))][layer].add(expert)
    rows = []
    for (pattern, dtype, shape), by_layer in sorted(groups.items()):
        expert_sets = {frozenset(v) for v in by_layer.values()}
        assert len(expert_sets) == 1, (pattern, "uneven expert sets")
        experts = next(iter(expert_sets))
        if experts == {None}:
            count = "-"
        else:
            assert experts == set(range(len(experts))), (pattern, "non-contiguous experts")
            count = str(len(experts))
        layers = set(by_layer)
        indices = "-" if layers == {None} else ranges(layers)
        rows.append((pattern, dtype, shape, indices, count))
    expanded = expand(rows)
    original = {k: (v[1], ",".join(map(str, v[2]))) for k, v in census.items()}
    assert expanded == original, "fixture does not reproduce the census"
    total = sum(v[3] for v in census.values())
    with open(out_path, "w") as f:
        f.write(f"# {REPO}@{REV}: every safetensors header tensor, grouped by name class.\n")
        f.write("# Generated by research/modelplan-onboarding-dsv41-20261109/census_classes.py;\n")
        f.write("# {L} = layer, DSpark block or ViT block index, {E} = expert 0..count-1.\n")
        f.write(f"# tensors\t{len(census)}\n# bytes\t{total}\n")
        f.write("pattern\tdtype\tshape\tindices\texperts\n")
        for row in rows:
            f.write("\t".join(row) + "\n")
    print(f"{len(rows)} classes, {len(census)} tensors, {total} bytes -> {out_path}")


if __name__ == "__main__":
    main(*sys.argv[1:])
