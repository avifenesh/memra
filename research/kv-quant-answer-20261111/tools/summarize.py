#!/usr/bin/env python3
"""Summarize the answer-position cells (memra#1177).

Programs: a = prefill over f32 K/V (the reference), b = the prime over the quantized cache,
c = the served batch decode over a prime-written cache. The teacher-forced sequence is the
served prompt followed by the served answer (plain arm), so at an answer row the next id is
the token the server sent.

Rows: "answer" rows are the positions whose logits chose an answer token (first answer row =
prompt length - 1), the `<|im_end|>` that ended the answer included; the row after the last
id has no next token and is left out. "in-turn" rows are the 2,048 rows before the first
answer row; they sit inside the user turn (the document's tail, the question and the template).

Per cell: the answer rows where each program's top-1 differs from the served token, both
programs' top-2 margins there, the spread distribution (the gate's `delta@ids`: max |x - y|
over both programs' top-2 ids) at answer rows against in-turn rows, and, per differing row,
whether it falls inside a known value and whether the served answer is right.

One percentile everywhere: sorted[round((n - 1) * p)].

The in-turn rows are also split at the end of the document: "document" rows choose a
document token, "question" rows choose a token of the closing tag, the question or the template.

usage: summarize.py RUNS_DIR REQUESTS_DIR TOKENIZER_JSON OUT_DIR CELL...
"""
import gzip
import json
import sys
from pathlib import Path

from tokenizers import Tokenizer


def q(x) -> str:
    """A token or text as a code span inside a markdown table cell (pipes escaped)."""
    return "`" + repr(x).replace("|", "\\|") + "`"


def pct(xs, p):
    s = sorted(xs)
    return s[round((len(s) - 1) * p)] if s else None


def margin(prog):
    t = prog["top"]
    return t[0][1] - t[1][1]


def load_json(path: Path):
    """PATH, or PATH.gz as committed."""
    if path.exists():
        return json.load(open(path))
    return json.load(gzip.open(str(path) + ".gz", "rt"))


def rows_of(d: Path):
    p = d / "rows.jsonl"
    f = open(p) if p.exists() else gzip.open(d / "rows.jsonl.gz", "rt")
    return [json.loads(line) for line in f]


def dist(xs):
    return {
        "n": len(xs),
        "median": pct(xs, 0.5),
        "p90": pct(xs, 0.9),
        "p99": pct(xs, 0.99),
        "max": max(xs) if xs else None,
        "over_1": sum(x > 1 for x in xs),
        "over_3": sum(x > 3 for x in xs),
    }


def main() -> None:
    runs, reqdir, tokp, out = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3], Path(sys.argv[4])
    cells = sys.argv[5:]
    questions = json.load(open(reqdir / "questions.json"))
    tok = Tokenizer.from_file(tokp)
    out.mkdir(parents=True, exist_ok=True)
    summary = []
    md = ["# Answer-position cells: per-cell detail (generated by tools/summarize.py)", ""]
    for cell in cells:
        d = runs / cell
        meta = json.load(open(d / "meta.json"))
        served = load_json(d / "served-plain.json")
        default = load_json(d / "served-default.json")
        doc = cell.split("-")[0]
        known = questions[doc]["known"]
        ids = load_json(d / "ids.json")
        rows = rows_of(d)
        fa = meta["first_answer_row"]
        ans = [r for r in rows if r["row"] >= fa and r["next"] is not None]
        inturn = [r for r in rows if r["row"] < fa]
        assert len(inturn) == 2048, (cell, len(inturn))
        # First id after the document: the longest prefix of the ids that decodes to a prefix
        # of the rendered text ending with the document (a boundary merge can join the
        # document's last newline to the closing tag), so every "document" row chooses a
        # document token.
        content = json.load(open(reqdir / f"{cell}.request.json"))["messages"][0]["content"]
        head = "<|im_start|>user\n" + content[: content.index("</tool_output>")]
        doc_end = len(tok.encode(head, add_special_tokens=False).ids) + 1
        while not head.startswith(tok.decode(ids[:doc_end], skip_special_tokens=False)):
            doc_end -= 1
        docrows = [r for r in inturn if r["row"] + 1 < doc_end]
        qrows = [r for r in inturn if r["row"] + 1 >= doc_end]
        text = served["answer_text"]
        right = {k: (v in text) for k, v in known.items()}

        # Character span of each answer token, to place a row inside a known value.
        ans_ids = ids[fa + 1 :]
        spans, pos = [], 0
        for i in range(len(ans_ids)):
            piece = tok.decode(ans_ids[: i + 1], skip_special_tokens=False)
            spans.append((pos, len(piece)))
            pos = len(piece)
        dec_answer = tok.decode(ans_ids, skip_special_tokens=False)
        value_spans = {}
        for k, v in known.items():
            at = dec_answer.find(v)
            if at >= 0:
                value_spans[k] = (at, at + len(v))

        def inside(j):
            s, e = spans[j]
            return [k for k, (vs, ve) in value_spans.items() if s < ve and e > vs]

        def tokstr(i):
            return tok.decode([i], skip_special_tokens=False)

        res = {
            "cell": cell,
            "prompt_tokens": meta["prompt_tokens"],
            "answer_tokens": meta["answer_tokens"],
            "finish_reason": meta["finish_reason"],
            "answer_rows": len(ans),
            "default_equals_plain_text": meta["default_equals_plain_text"],
            "answer_text": text,
            "default_answer_text": default["answer_text"],
            "known": known,
            "served_answer_right": right,
        }
        res["document_end_id"] = doc_end
        res["in_turn_document_rows"] = len(docrows)
        res["in_turn_question_rows"] = len(qrows)
        res["document_rows_im_end_top1_a"] = sum(r["a"]["top"][0][0] == 248046 for r in docrows)
        # Document rows split by a's top-1: `<|im_end|>` (the model would close the turn there)
        # or any other token.
        for lab, sel in (
            ("im_end", [r for r in docrows if r["a"]["top"][0][0] == 248046]),
            ("other", [r for r in docrows if r["a"]["top"][0][0] != 248046]),
        ):
            res[f"document_{lab}_ac"] = dist([r["ac"]["delta"] for r in sel])
            res[f"document_{lab}_ac_flips"] = sum(r["ac"]["flip"] for r in sel)
            res[f"document_{lab}_a_margin_median"] = pct([margin(r["a"]) for r in sel], 0.5)
        for p in ("a", "b", "c"):
            res[f"{p}_top1_differs_from_served"] = sum(r[p]["top"][0][0] != r["next"] for r in ans)
        for pair in ("ab", "ac", "bc"):
            res[f"spread_{pair}_answer"] = dist([r[pair]["delta"] for r in ans])
            res[f"spread_{pair}_in_turn"] = dist([r[pair]["delta"] for r in inturn])
            res[f"spread_{pair}_document"] = dist([r[pair]["delta"] for r in docrows])
            res[f"spread_{pair}_question"] = dist([r[pair]["delta"] for r in qrows])
            res[f"flips_{pair}_document"] = sum(r[pair]["flip"] for r in docrows)
            res[f"flips_{pair}_question"] = sum(r[pair]["flip"] for r in qrows)
            res[f"flips_{pair}_answer"] = sum(r[pair]["flip"] for r in ans)
            res[f"flips_{pair}_in_turn"] = sum(r[pair]["flip"] for r in inturn)
        for p in ("a", "b", "c"):
            ms = [margin(r[p]) for r in ans]
            res[f"margin_{p}_answer"] = {"min": min(ms), "p10": pct(ms, 0.1), "median": pct(ms, 0.5)}
        res["answer_rows_ac_spread_over_smaller_margin"] = sum(
            r["ac"]["delta"] > min(margin(r["a"]), margin(r["c"])) for r in ans
        )
        wide = []
        for r in ans:
            if max(r[q]["delta"] for q in ("ab", "ac", "bc")) > 1 or min(margin(r[p]) for p in ("a", "b", "c")) < 1:
                j = r["row"] - fa
                wide.append(
                    {
                        "row": r["row"],
                        "answer_pos": j,
                        "before": tok.decode(ans_ids[max(0, j - 12) : j], skip_special_tokens=False),
                        "served": tokstr(r["next"]),
                        "a_second": tokstr(r["a"]["top"][1][0]),
                        "c_second": tokstr(r["c"]["top"][1][0]),
                        "a_margin": margin(r["a"]),
                        "b_margin": margin(r["b"]),
                        "c_margin": margin(r["c"]),
                        "spread_ab": r["ab"]["delta"],
                        "spread_ac": r["ac"]["delta"],
                        "spread_bc": r["bc"]["delta"],
                        "inside_value": inside(j),
                    }
                )
        res["answer_rows_spread_over_1"] = wide
        # Rows that choose a token of a known value (a digit of a number, a piece of a name).
        val = [r for r in ans if inside(r["row"] - fa)]
        res["value_rows"] = len(val)
        for p in ("a", "b", "c"):
            res[f"value_rows_min_margin_{p}"] = min(margin(r[p]) for r in val) if val else None
        res["value_rows_ac_spread_max"] = max(r["ac"]["delta"] for r in val) if val else None
        # Value rows whose runner-up is `<|im_end|>`: the program would end the answer there.
        for p in ("a", "b", "c"):
            imr = [r for r in val if r[p]["top"][1][0] == 248046]
            res[f"value_rows_im_end_runner_up_{p}"] = len(imr)
            res[f"value_rows_im_end_runner_up_{p}_margin_range"] = (
                [min(margin(r[p]) for r in imr), max(margin(r[p]) for r in imr)] if imr else None
            )
        diffs = []
        for r in ans:
            j = r["row"] - fa
            if all(r[p]["top"][0][0] == r["next"] for p in ("a", "b", "c")):
                continue
            ctx = tok.decode(ans_ids[max(0, j - 12) : j], skip_special_tokens=False)
            diffs.append(
                {
                    "row": r["row"],
                    "answer_pos": j,
                    "before": ctx,
                    "served": tokstr(r["next"]),
                    "a_top1": tokstr(r["a"]["top"][0][0]),
                    "a_margin": margin(r["a"]),
                    "a_served_logit_gap": r["a"]["top"][0][1] - r["a"]["next_logit"],
                    "a_served_rank": r["a"]["next_rank"],
                    "b_top1": tokstr(r["b"]["top"][0][0]),
                    "b_margin": margin(r["b"]),
                    "c_top1": tokstr(r["c"]["top"][0][0]),
                    "c_margin": margin(r["c"]),
                    "spread_ab": r["ab"]["delta"],
                    "spread_ac": r["ac"]["delta"],
                    "spread_bc": r["bc"]["delta"],
                    "inside_value": inside(j),
                }
            )
        res["differing_rows"] = diffs
        summary.append(res)

        md += [f"## {cell}", ""]
        md += [
            f"Prompt {meta['prompt_tokens']} tokens, answer {meta['answer_tokens']} tokens "
            f"(finish `{meta['finish_reason']}`), {len(ans)} answer rows, 2048 in-turn rows ({len(docrows)} document, {len(qrows)} question). "
            f"Default-arm text equals the plain arm's: {meta['default_equals_plain_text']}.",
            "",
            "Served answer (plain arm):",
            "",
            "```",
            text,
            "```",
            "",
            "Known values and whether the served answer contains each: "
            + ", ".join(f"{k} `{v}` {'yes' if right[k] else 'NO'}" for k, v in known.items()),
            "",
            f"Answer rows where the top-1 differs from the served token: a {res['a_top1_differs_from_served']}, "
            f"b {res['b_top1_differs_from_served']}, c {res['c_top1_differs_from_served']}.",
            "",
            "| pair | rows | flips | spread median | p90 | p99 | max | rows > 1 | rows > 3 |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for pair in ("ab", "ac", "bc"):
            for where in ("answer", "question", "document", "in_turn"):
                s = res[f"spread_{pair}_{where}"]
                md.append(
                    f"| {pair} {where.replace('_', '-')} | {s['n']} | {res[f'flips_{pair}_{where}']} | "
                    f"{s['median']:.3f} | {s['p90']:.3f} | {s['p99']:.3f} | {s['max']:.3f} | {s['over_1']} | {s['over_3']} |"
                )
        md.append("")
        md.append(
            "Document rows by a's top-1, a/c spread: "
            + "; ".join(
                f"{lab} {res[f'document_{lab}_ac']['n']} rows, median {res[f'document_{lab}_ac']['median']:.3f}, "
                f"p90 {res[f'document_{lab}_ac']['p90']:.3f}, max {res[f'document_{lab}_ac']['max']:.3f}, "
                f"{res[f'document_{lab}_ac_flips']} flips, a margin median {res[f'document_{lab}_a_margin_median']:.2f}"
                for lab in ("im_end", "other")
                if res[f"document_{lab}_ac"]["n"]
            )
            + "."
        )
        md.append("")
        md.append(
            f"Value rows (choosing a token of a known value): {res['value_rows']}. Smallest margin there, "
            f"a / b / c: "
            + " / ".join(f"{res[f'value_rows_min_margin_{p}']:.2f}" for p in ("a", "b", "c") if res["value_rows"])
            + ". Value rows whose runner-up is `<\\|im_end\\|>`: "
            + ", ".join(
                f"{p} {res[f'value_rows_im_end_runner_up_{p}']}"
                + (
                    f" (margins {res[f'value_rows_im_end_runner_up_{p}_margin_range'][0]:.2f} to "
                    f"{res[f'value_rows_im_end_runner_up_{p}_margin_range'][1]:.2f})"
                    if res[f"value_rows_im_end_runner_up_{p}"]
                    else ""
                )
                for p in ("a", "b", "c")
            )
            + "."
        )
        md.append("")
        ma, mb, mc = res["margin_a_answer"], res["margin_b_answer"], res["margin_c_answer"]
        md += [
            f"Top-2 margin at answer rows, min / p10 / median: a {ma['min']:.2f} / {ma['p10']:.2f} / {ma['median']:.2f}, "
            f"b {mb['min']:.2f} / {mb['p10']:.2f} / {mb['median']:.2f}, c {mc['min']:.2f} / {mc['p10']:.2f} / {mc['median']:.2f}. "
            f"Answer rows where the a/c spread exceeds the smaller of the two margins: "
            f"{res['answer_rows_ac_spread_over_smaller_margin']}.",
            "",
        ]
        if wide:
            md += [
                "Answer rows with a spread above 1 in any pair or a top-2 margin under 1 in any program:",
                "",
                "| row | pos | text before | served | runner-up a / c | margin a | b | c | spread ab | ac | bc | inside value |",
                "|---|---|---|---|---|---|---|---|---|---|---|---|",
            ]
            for x in wide:
                md.append(
                    f"| {x['row']} | {x['answer_pos']} | {q(x['before'])} | {q(x['served'])} | {q(x['a_second'])} / {q(x['c_second'])} | {x['a_margin']:.2f} | "
                    f"{x['b_margin']:.2f} | {x['c_margin']:.2f} | {x['spread_ab']:.2f} | {x['spread_ac']:.2f} | "
                    f"{x['spread_bc']:.2f} | {', '.join(x['inside_value']) or '-'} |"
                )
            md.append("")
        if diffs:
            md += [
                "| row | pos | text before | served | a top-1, margin | a: top-1 minus served | b top-1, margin | c top-1, margin | spread ab | ac | bc | inside value |",
                "|---|---|---|---|---|---|---|---|---|---|---|---|",
            ]
            for x in diffs:
                md.append(
                    f"| {x['row']} | {x['answer_pos']} | {q(x['before'])} | {q(x['served'])} | "
                    f"{q(x['a_top1'])} {x['a_margin']:.2f} | {x['a_served_logit_gap']:.2f} (rank {x['a_served_rank']}) | "
                    f"{q(x['b_top1'])} {x['b_margin']:.2f} | {q(x['c_top1'])} {x['c_margin']:.2f} | "
                    f"{x['spread_ab']:.2f} | {x['spread_ac']:.2f} | {x['spread_bc']:.2f} | {', '.join(x['inside_value']) or '-'} |"
                )
            md.append("")
        else:
            md += ["No answer row where any program's top-1 differs from the served token.", ""]
    (out / "SUMMARY.jsonl").write_text("".join(json.dumps(s, ensure_ascii=False) + "\n" for s in summary))
    (out / "SUMMARY.md").write_text("\n".join(md).rstrip("\n") + "\n")
    for s in summary:
        print(
            s["cell"],
            "answer_rows", s["answer_rows"],
            "differs a/b/c", s["a_top1_differs_from_served"], s["b_top1_differs_from_served"], s["c_top1_differs_from_served"],
            "right", s["served_answer_right"],
        )


if __name__ == "__main__":
    main()
