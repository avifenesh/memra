"""Agentic cell, the ab_agent.py run shape, with per-request status so one HTTP error does not end the run.

Same bodies as the prefix-budget-20261107 lane's agentic.py (messages, tools, max_tokens, temperature,
enable_thinking, seed = 1234 + k): every turn is primed once with max_tokens=1 at the cell's concurrency,
then (unless --prime-only) the measured pass sends the same bodies again. Every row keeps its start
time, first-token time (first content, reasoning or tool-call delta; SSE comments ignored), end time,
HTTP status and error, usage, and a sha256 of the generated bytes.

  python3 agentic2.py WORKLOAD.json OUT.json --users 8 [--temperature 1.0] [--max-tokens 768] [--prime-only]
"""
import argparse, hashlib, json, re, statistics, sys, time, urllib.error, urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument('workload')
ap.add_argument('out')
ap.add_argument('--port', type=int, default=18187)
ap.add_argument('--users', type=int, default=1)
ap.add_argument('--think', type=int, default=1)
ap.add_argument('--temperature', type=float, default=1.0)
ap.add_argument('--max-tokens', type=int, default=768)
ap.add_argument('--seed', type=int, default=1234)
ap.add_argument('--prime-only', action='store_true')
a = ap.parse_args()
BASE = f'http://127.0.0.1:{a.port}'


def metrics():
    raw = urllib.request.urlopen(BASE + '/metrics', timeout=15).read().decode()
    out = {}
    for m in re.finditer(r"^([A-Za-z_:]*(?:prefix_cache|evict|reclaim|deadline|shed)[A-Za-z_:]*)(?:\{[^}]*\})? ([0-9.e+-]+)$", raw, re.M):
        out[m.group(1)] = out.get(m.group(1), 0.0) + float(m.group(2))
    return out


work = json.loads(Path(a.workload).read_text())
kw = {'enable_thinking': bool(a.think)}
bodies = [{'model': 'gate', 'messages': w['messages'], 'tools': w['tools'], 'max_tokens': a.max_tokens,
           'temperature': a.temperature, 'chat_template_kwargs': kw, 'seed': a.seed + k}
          for k, w in enumerate(work)]


def stream(k, body, phase):
    body = dict(body, stream=True, stream_options={'include_usage': True, 'continuous_usage_stats': True})
    row = {'k': k, 'session': work[k]['session'], 'turn': work[k]['turn'], 'phase': phase,
           't_start': time.time(), 'ttft_s': None, 'wall_s': None, 'status': None, 'error': None,
           'prompt_tokens': None, 'cached': None, 'completion_tokens': None, 'finish': None, 'sha256': None}
    req = urllib.request.Request(BASE + '/v1/chat/completions', data=json.dumps(body).encode(),
                                 headers={'Content-Type': 'application/json'})
    h = hashlib.sha256()
    usage, finish, t_last = None, None, None
    try:
        with urllib.request.urlopen(req, timeout=3600) as r:
            row['status'] = r.status
            for raw in r:
                line = raw.decode().strip()
                if not line.startswith('data:') or line == 'data: [DONE]':
                    continue
                v = json.loads(line[5:])
                if v.get('error'):
                    row['error'] = json.dumps(v['error'])[:500]
                    continue
                usage = v.get('usage') or usage
                for c in v.get('choices') or []:
                    finish = c.get('finish_reason') or finish
                    d = c.get('delta') or {}
                    piece = (d.get('reasoning_content') or d.get('reasoning') or '') + '\x00' + (d.get('content') or '')
                    tc = d.get('tool_calls')
                    if piece != '\x00' or tc:
                        now = time.time()
                        if row['ttft_s'] is None:
                            row['ttft_s'] = now - row['t_start']
                        t_last = now
                        h.update(piece.encode())
                        if tc:
                            h.update(json.dumps(tc, sort_keys=True).encode())
    except urllib.error.HTTPError as e:
        row['status'] = e.code
        row['error'] = e.read().decode(errors='replace')[:500]
    except Exception as e:  # noqa: BLE001 - a transport failure is a row, not the end of the cell
        row['error'] = repr(e)[:500]
    row['wall_s'] = time.time() - row['t_start']
    if usage:
        row['prompt_tokens'] = usage.get('prompt_tokens')
        row['cached'] = (usage.get('prompt_tokens_details') or {}).get('cached_tokens')
        row['completion_tokens'] = usage.get('completion_tokens')
    row['finish'] = finish
    row['sha256'] = h.hexdigest()
    if row['ttft_s'] is not None and t_last and row['completion_tokens'] and row['completion_tokens'] > 1:
        row['gen_tps'] = (row['completion_tokens'] - 1) / max(t_last - row['t_start'] - row['ttft_s'], 1e-6)
    return row


def run_pass(phase, overrides):
    t0 = time.time()
    with ThreadPoolExecutor(a.users) as pool:
        rows = list(pool.map(lambda kb: stream(kb[0], dict(kb[1], **overrides), phase), enumerate(bodies)))
    return rows, time.time() - t0


def summarize(rows, wall):
    ok = [r for r in rows if r['status'] == 200 and r['ttft_s'] is not None and not r['error']]
    t = sorted(r['ttft_s'] for r in ok)
    pct = lambda v, q: v[min(len(v) - 1, int(q * len(v)))] if v else None
    toks = sum(r['completion_tokens'] or 0 for r in ok)
    s = {'rows': len(rows), 'ok': len(ok), 'status_counts': {}, 'wall_s': round(wall, 1),
         'ttft_ms_p50': round(1000 * pct(t, 0.5), 1) if t else None,
         'ttft_ms_p95': round(1000 * pct(t, 0.95), 1) if t else None,
         'ttft_ms_p99': round(1000 * pct(t, 0.99), 1) if t else None,
         'ttft_ms_max': round(1000 * t[-1], 1) if t else None,
         'tokens': toks, 'agg_tok_s': round(toks / wall, 2) if wall else None,
         'cached_tokens': sum(r['cached'] or 0 for r in ok), 'prompt_tokens': sum(r['prompt_tokens'] or 0 for r in ok),
         'hits': sum(1 for r in ok if (r['cached'] or 0) > 0)}
    g = [r['gen_tps'] for r in ok if r.get('gen_tps')]
    s['per_user_gen_tps_median'] = round(statistics.median(g), 2) if g else None
    for r in rows:
        key = str(r['status']) + ('' if not r['error'] else '+err')
        s['status_counts'][key] = s['status_counts'].get(key, 0) + 1
    return s


m0 = metrics()
primes, prime_wall = run_pass('prime', {'max_tokens': 1})
m1 = metrics()
out = {'args': vars(a), 'prime': summarize(primes, prime_wall),
       'prime_metrics_delta': {k: m1.get(k, 0) - m0.get(k, 0) for k in m1}}
rows = primes
if not a.prime_only:
    meas, wall = run_pass('measure', {})
    m2 = metrics()
    out['measure'] = summarize(meas, wall)
    out['measure_metrics_delta'] = {k: m2.get(k, 0) - m1.get(k, 0) for k in m2}
    rows = primes + meas
json.dump({'cell': out, 'rows': rows}, open(a.out, 'w'), indent=1)
print(json.dumps(out), flush=True)
