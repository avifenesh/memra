"""Compare greedy outputs across runs, row by row.

Agentic rows (agentic2.py): key (phase, k), compare `sha256` of the generated bytes.
Mixed rows (mixed.py): key `tag`, compare `text`; batch rows exist only where both runs served the tag.

  python3 exact_cmp.py RUN_A RUN_B [--phase measure]
Prints matched/compared, and the keys that differ.
"""
import argparse
import json
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument('a')
ap.add_argument('b')
ap.add_argument('--phase', default=None, help='agentic only: prime or measure (default both)')
a = ap.parse_args()


def load(d):
    j = json.load(open(Path(d) / 'rows.json'))
    rows = j['rows'] if isinstance(j, dict) else j
    out = {}
    for r in rows:
        if 'tag' in r:
            out[r['tag']] = r.get('text')
        else:
            if a.phase and r['phase'] != a.phase:
                continue
            if r.get('status') != 200 or r.get('error'):
                continue
            out[(r['phase'], r['k'])] = r['sha256']
    return out


x, y = load(a.a), load(a.b)
keys = sorted(set(x) & set(y), key=str)
diff = [k for k in keys if x[k] != y[k]]
print(json.dumps({'a': Path(a.a).name, 'b': Path(a.b).name, 'compared': len(keys),
                  'matched': len(keys) - len(diff), 'only_a': len(set(x) - set(y)),
                  'only_b': len(set(y) - set(x)), 'differ': [str(k) for k in diff]}))
