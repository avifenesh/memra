"""Compress census/header-census.tsv into the pack fixture
crates/memra-gguf/src/model_packs/hy_v4_flash/fixtures/census-classes.tsv.

Every name with a layer index after `model.layers.`, `model.dfly_layers.` or `vit.layers.` becomes a
`{L}` pattern; rows that share pattern, dtype and shape collapse into one line with the list of
indices as ranges. The script refuses to write unless the fixture expands back to exactly the
header census (names, dtypes, shapes) and its tensor and byte totals.

    python3 -I census_classes.py census/header-census.tsv ../../crates/memra-gguf/src/model_packs/hy_v4_flash/fixtures/census-classes.tsv
"""

import re
import sys
from collections import defaultdict

src, dst = sys.argv[1], sys.argv[2]
rows = {}
total_bytes = 0
header = []
for line in open(src):
    line = line.rstrip("\n")
    if line.startswith("#"):
        header.append(line)
        continue
    if line.startswith("name\t"):
        continue
    name, dtype, shape, _shard, nbytes = line.split("\t")
    rows[name] = (dtype, shape)
    total_bytes += int(nbytes)

INDEX = re.compile(r"^(?:model\.layers|model\.dfly_layers|vit\.layers)\.(\d+)\.")
groups = defaultdict(list)
for name, (dtype, shape) in rows.items():
    m = INDEX.search(name)
    if m:
        pattern = name[: m.start(1)] + "{L}" + name[m.end(1):]
        groups[(pattern, dtype, shape)].append(int(m.group(1)))
    else:
        groups[(name, dtype, shape)].append(None)


def ranges(values):
    values = sorted(values)
    out, start, prev = [], values[0], values[0]
    for v in values[1:]:
        if v == prev + 1:
            prev = v
            continue
        out.append(f"{start}-{prev}" if start != prev else f"{start}")
        start = prev = v
    out.append(f"{start}-{prev}" if start != prev else f"{start}")
    return ",".join(out)


lines = []
for (pattern, dtype, shape), idx in sorted(groups.items()):
    indices = "-" if idx == [None] else ranges(idx)
    lines.append(f"{pattern}\t{dtype}\t{shape}\t{indices}")

# Round trip before writing.
expanded = {}
for line in lines:
    pattern, dtype, shape, indices = line.split("\t")
    if indices == "-":
        names = [pattern]
    else:
        names = []
        for part in indices.split(","):
            a, _, b = part.partition("-")
            for i in range(int(a), int(b or a) + 1):
                names.append(pattern.replace("{L}", str(i)))
    for n in names:
        assert n not in expanded, n
        expanded[n] = (dtype, shape)
if expanded != rows:
    sys.exit("fixture does not expand back to the header census")

with open(dst, "w") as f:
    f.write(header[0].replace("every safetensors header tensor", "every safetensors header tensor, grouped by name class") + "\n")
    f.write("# Generated by research/modelplan-onboarding-hy4flash-20261119/census_classes.py from census/header-census.tsv;\n")
    f.write("# {L} = trunk layer, DFly2 block or ViT layer index; shape '-' = a scalar.\n")
    f.write(f"# tensors\t{len(rows)}\n# bytes\t{total_bytes}\n")
    f.write("pattern\tdtype\tshape\tindices\n")
    f.write("\n".join(lines) + "\n")
print(f"{len(lines)} classes, {len(rows)} tensors, {total_bytes} bytes")
