#!/usr/bin/env python3
"""Generate crates/memra-engine/env-registry.txt, the boot audit's MEMRA_* registry, from docs/FLAGS.md.

    python3 tools/gen-env-registry.py           # rewrite the registry
    python3 tools/gen-env-registry.py --check   # exit 1 when the committed registry is stale

The engine's build script reads the generated file, not the catalog, so a docs/FLAGS.md edit that
leaves the registry unchanged is a docs change. An edit that changes it shows up as a diff in the
engine crate. The pre-push hook and CI run --check through tools/check-flags.sh.

The rules (moved verbatim from crates/memra-engine/build.rs, where they were the parser):
- A `MEMRA_...` token anywhere outside the "Removed" ledgers documents a name; a trailing `*`
  documents a prefix family. That is what tools/check-flags.sh accepts, and the audit must not
  refuse a name the census passed.
- A definition is the first cell of a live table row (`| \\`MEMRA_X\\` | ...`).
- A ledger is any heading, at any level, whose text starts with `Removed`. It ends at the next
  heading of the same or a shallower level. Inside it, a definition block is a `- ` bullet, a
  `| ` row or a line that opens with a backticked name, together with its indented continuation
  lines, and every non-prefix name in the block is retired, minus names that still have a live
  definition. The first ledger heading that names a door is its pointer.
- A live row whose second cell opens with REMOVED retires its first-cell names, with the row as
  its ledger ("row marked REMOVED ...").
- Retired names leave the legal set.

The owned families (prefixes the workspace reads under three or more names) come from the code
and stay in build.rs.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FLAGS = ROOT / "docs/FLAGS.md"
OUT = ROOT / "crates/memra-engine/env-registry.txt"
HEADER = ("# Generated by tools/gen-env-registry.py from docs/FLAGS.md; do not edit. Edit the\n"
          "# catalog and rerun the tool. Lines: legal <name>, prefix <name_>, retired <name>\\t<ledger>.\n")


# Rust's char::is_whitespace (Unicode White_Space), which str::trim uses. Python's str.strip()
# also strips U+001C..U+001F, so the parser trims with this set to stay byte-equal with the
# Rust parser it replaced.
RUST_WS = ("\t\n\x0b\x0c\r \x85\xa0\u1680\u2000\u2001\u2002\u2003\u2004\u2005\u2006\u2007"
           "\u2008\u2009\u200a\u2028\u2029\u202f\u205f\u3000")


def rtrim_ws(s):
    return s.strip(RUST_WS)


def tokens(cell):
    """MEMRA_ tokens in a string: (name, is_prefix). Mirrors build.rs byte for byte."""
    out = []
    i = 0
    n = len(cell)
    while True:
        rel = cell.find("MEMRA_", i)
        if rel < 0:
            break
        start = rel
        end = start
        while end < n and (("A" <= cell[end] <= "Z") or ("0" <= cell[end] <= "9") or cell[end] == "_"):
            end += 1
        prefix = end < n and cell[end] == "*"
        stem = cell[start:end].rstrip("_")
        if len(stem) > len("MEMRA"):
            out.append((stem + "_" if prefix else stem, prefix))
        i = max(end, start + 1)
    return out


def heading(line):
    level = len(line) - len(line.lstrip("#"))
    if level == 0 or level > 6 or not line[level:].startswith(" "):
        return None
    return level, rtrim_ws(line[level:])


def lines_of(text):
    """Rust str::lines(): split on \\n, drop one trailing \\r, no empty last line."""
    parts = text.split("\n")
    if parts and parts[-1] == "":
        parts.pop()
    return [p[:-1] if p.endswith("\r") else p for p in parts]


def parse(text):
    """docs/FLAGS.md text -> (legal names, prefixes, [(retired name, ledger)]), all sorted."""
    defs, legal, prefixes = set(), set(), set()
    ledger = {}
    removed = None  # (level, heading text)
    in_block = False
    for line in lines_of(text):
        h = heading(line)
        if h is not None:
            level, htext = h
            in_block = False
            if removed is not None and level > removed[0] and not htext.startswith("Removed"):
                pass
            elif htext.startswith("Removed"):
                removed = (level, htext)
            else:
                removed = None
            continue
        if removed is not None:
            starts = line.startswith("- ") or line.startswith("| ") or line.startswith("`MEMRA_")
            continues = in_block and line.startswith(" ") and rtrim_ws(line) != ""
            if starts or continues:
                in_block = True
                for name, prefix in tokens(line):
                    if not prefix:
                        ledger.setdefault(name, removed[1])
            else:
                in_block = False
            continue
        for name, prefix in tokens(line):
            (prefixes if prefix else legal).add(name)
        if line.startswith("| "):
            cells = line[2:].split("|")
            first = cells[0] if cells else ""
            second = rtrim_ws(cells[1] if len(cells) > 1 else "").lstrip("*")
            removed_row = second.startswith("REMOVED")
            for name, prefix in tokens(first):
                if prefix:
                    continue
                if removed_row:
                    ledger.setdefault(name, "row marked " + second.rstrip("*"))
                else:
                    defs.add(name)
    retired = sorted((n, h) for n, h in ledger.items() if n not in defs)
    for n, _ in retired:
        legal.discard(n)
    return sorted(legal), sorted(prefixes), retired


class RegistryError(Exception):
    pass


def render(text):
    # The size floors (more than 200 legal names, at least one retired door) are asserted by
    # build.rs on the file it reads, so a parser break fails the engine build, not only here.
    legal, prefixes, retired = parse(text)
    out = [HEADER]
    out += [f"legal\t{n}\n" for n in legal]
    out += [f"prefix\t{p}\n" for p in prefixes]
    for n, h in retired:
        if any(c in h for c in "\t\n\r"):
            raise RegistryError(f"ledger heading for {n} holds a tab, CR or newline: {h!r}")
        out.append(f"retired\t{n}\t{h}\n")
    return "".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail when the committed registry is stale")
    ap.add_argument("--flags", type=Path, default=FLAGS, help=argparse.SUPPRESS)
    ap.add_argument("--out", type=Path, default=OUT, help=argparse.SUPPRESS)
    args = ap.parse_args()
    # Bytes, decoded without universal newlines: Python's text mode turns a lone CR into a line
    # break, and the Rust parser this replaces did not.
    try:
        want = render(args.flags.read_bytes().decode("utf-8"))
    except (OSError, UnicodeDecodeError, RegistryError) as e:
        print(f"gen-env-registry: cannot build the registry: {e}", file=sys.stderr)
        return 2
    if args.check:
        have = args.out.read_bytes().decode("utf-8", errors="replace") if args.out.exists() else ""
        if have != want:
            print(f"gen-env-registry: {args.out.relative_to(ROOT) if args.out.is_relative_to(ROOT) else args.out} "
                  "is stale against docs/FLAGS.md; run python3 tools/gen-env-registry.py and commit it",
                  file=sys.stderr)
            return 1
        print(f"gen-env-registry: registry matches docs/FLAGS.md "
              f"({sum(1 for l in want.splitlines() if l.startswith('legal'))} legal, "
              f"{sum(1 for l in want.splitlines() if l.startswith('prefix'))} prefixes, "
              f"{sum(1 for l in want.splitlines() if l.startswith('retired'))} retired)")
        return 0
    args.out.write_bytes(want.encode("utf-8"))
    print(f"gen-env-registry: wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
