#!/usr/bin/env python3
"""Delta query over the impact map: which (family, route, device) cells a diff can reach, what
each needs (test kinds), what the ledger already proves for the exact code, and the minimal
model x route x device run set.

The map (docs/impact-map/map.json) is generated by tools/impact_map/build.py at some commit M.
For a diff base..head:

1. Every changed Rust/CUDA file is scanned at base and head (tools/impact_map/rust_items.py,
   cu_items.py; stdlib only). An item changes when its comment-free token hash moves.
   Comment-only and rustfmt-only edits change no hash and reach no cell.
2. A changed item known to the map takes the item's REACH (the cells that can execute it). When
   the item's base hash equals its hash at M, the changed lines are matched against the map's
   predicate regions, and a change that sits entirely inside narrowing arms takes only those arms'
   cells. An item the map does not know (new, renamed) takes the union of its file's items, and a
   file the map does not know reaches every cell. Removed items take their base reach.
3. Effects of the changed items pick the test kinds (numeric -> argmax and route gates, speed ->
   perf A/B, memory -> device memory qualification, policy -> serve-smoke, CUDA/FFI -> kernel-check).

Why a map built at an older commit stays safe: a change that makes a new caller reach an item
changes that caller, and the caller already carries its own reach. A change that only removes
an edge leaves the map wider than the truth, never narrower. The remaining exceptions are edges
the static graph cannot see (string-keyed or env-selected dispatch the map lists under
dynamic_edges); those items are kept wide.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import cu_items  # noqa: E402
import rust_items  # noqa: E402

MAP_PATH = "docs/impact-map/map.json"
MODELS_PATH = "docs/impact-map/models.json"
LEDGER_PATH = "docs/impact-map/ledger.json"
CU_PREFIX = "crates/memra-engine/"
SCHEMA = "memra-impact-delta-v1"

# effect -> test kinds; the route gates name the gate a route's numeric change needs
EFFECT_TESTS = {
    "numeric": ("run-gen-argmax",),
    "speed": ("perf-ab",),
    "memory": ("memory-qual",),
    "policy": ("serve-smoke",),
    "observability": (),
    "none": (),
}
ROUTE_TESTS = {
    "mtp": ("run-spec",),
    "dflash": ("run-spec",),
    "eagle": ("run-spec",),
    "ngram": ("run-spec",),
    "glm5_spec": ("run-spec",),
    "batch": ("serve-smoke",),
    "prefix_cache": ("serve-smoke",),
    "constrained": ("serve-smoke",),
    "tools": ("serve-smoke",),
    "http_api": ("serve-smoke",),
    "vision": ("route-gate:vision",),
    "audio_asr": ("route-gate:audio_asr",),
    "audio_tts": ("route-gate:audio_tts",),
    "embed": ("route-gate:embed",),
    "rerank": ("route-gate:embed",),
    "tp": ("pair-gate",),
    "pp": ("pair-gate",),
    "ep": ("pair-gate",),
}


class DeltaError(ValueError):
    pass


def git(repo, *args, check=True, inp=None):
    r = subprocess.run(["git", "-C", str(repo), "-c", "core.quotePath=false", *args], capture_output=True, input=inp)
    if check and r.returncode != 0:
        raise DeltaError("git " + " ".join(args[:3]) + ": " + r.stderr.decode(errors="replace").strip())
    return r.stdout


def blob(repo, ref, path):
    r = subprocess.run(["git", "-C", str(repo), "show", f"{ref}:{path}"], capture_output=True)
    return r.stdout.decode("utf-8", "surrogateescape") if r.returncode == 0 else None


def load_json_at(repo, ref, path):
    text = blob(repo, ref, path)
    return None if text is None else json.loads(text)


def scan(path, text):
    """Items of one file keyed by stable id: {id: (hash, line_start, line_end)}."""
    if text is None:
        return {}
    if path.endswith(".rs"):
        recs = rust_items.scan(path, text)
    elif path.endswith((".cu", ".cuh", ".h")) and path.startswith(CU_PREFIX):
        recs = []
        for r in cu_items.scan(path[len(CU_PREFIX):], text):
            if r["kind"] == "pp":
                r = dict(r, hash=hashlib.sha256(r["text"].encode()).hexdigest()[:20])
            r["id"] = CU_PREFIX + r["id"]
            recs.append(r)
    else:
        return {}
    return {r["id"]: (r["hash"], r["line_start"], r["line_end"], r.get("test", False), r["kind"]) for r in recs}


def changed_lines(repo, base, head, path):
    """Base-side line numbers touched by the diff (deleted or next to an insertion)."""
    out = git(repo, "diff", "-U0", "--no-color", base, head, "--", path).decode(errors="replace")
    lines = set()
    for m in re.finditer(r"^@@ -(\d+)(?:,(\d+))? \+\d+(?:,\d+)? @@", out, re.M):
        start, n = int(m.group(1)), int(m.group(2) or 1)
        lines.update(range(start, start + n) if n else (start, start + 1))
    return lines


class Map:
    def __init__(self, data):
        if data.get("schema") != "memra-impact-map-v1":
            raise DeltaError(f"unknown map schema {data.get('schema')}")
        self.data = data
        self.items = data["items"]
        self.sets = data["reach_sets"]
        self.vocab = data["vocab"]
        self.by_file = {}
        for i, it in self.items.items():
            self.by_file.setdefault(it["f"], []).append(i)
        self.doors_hit = set()
        self.regions = {}
        for rg in data.get("regions", []):
            self.regions.setdefault(rg["file"], []).append(rg)

    def cells_of_set(self, idx):
        s = self.sets[idx]
        if s == "*":
            return {(f, r, d) for f in self.vocab["families"] for r in self.vocab["routes"] for d in self.vocab["devices"]}
        return {(f, r, d) for f, routes in s.items() for r, devs in routes.items() for d in devs}

    def item_cells(self, item_id):
        it = self.items.get(item_id)
        return None if it is None else self.cells_of_set(it["r"])

    def file_cells(self, path):
        ids = self.by_file.get(path)
        if not ids:
            return None
        out = set()
        for i in ids:
            out |= self.item_cells(i)
        return out

    def all_cells(self):
        return self.cells_of_set_all()

    def cells_of_set_all(self):
        v = self.vocab
        return {(f, r, d) for f in v["families"] for r in v["routes"] for d in v["devices"]}

    def region_cells(self, rg):
        v = self.vocab
        if rg.get("door") and rg["door"].get("default_reached") is False:
            return set()

        def pick(vals, universe):
            return list(universe) if not vals or "*" in vals else [x for x in vals if x in universe]
        return {(f, r, d) for f in pick(rg.get("families"), v["families"]) for r in pick(rg.get("routes"), v["routes"])
                for d in pick(rg.get("devices"), v["devices"])}

    def narrowed(self, item_id, lines):
        """Cells for a change at `lines` (base numbering, valid at the map commit) inside an item.
        Narrows only when every touched line sits in a labelled non-'none' region of this item."""
        it = self.items[item_id]
        full = self.item_cells(item_id)
        regs = [rg for rg in self.regions.get(it["f"], []) if rg.get("kind") != "none"
                and it["a"] <= rg["a"] <= it["b"]]
        if not lines or not regs:
            return full, False
        out = set()
        for ln in lines:
            best = None
            for rg in regs:
                # strictly after the region's first line: the first line usually carries the
                # branch condition, and a changed condition moves every arm, not just this one
                if rg["a"] < ln <= rg["b"] and (best is None or rg["b"] - rg["a"] < best["b"] - best["a"]):
                    best = rg
            if best is None:
                return full, False
            if best.get("door") and best["door"].get("default_reached") is False:
                self.doors_hit.add(best["door"].get("env", "?"))
            out |= self.region_cells(best)
        return out & full, True


def delta(repo, base, head, *, map_ref=None, paths=None, map_data=None, fingerprints=False):
    """The cells base..head can reach. map_ref defaults to base (the rules in force)."""
    map_ref = map_ref or base
    data = map_data if map_data is not None else load_json_at(repo, map_ref, MAP_PATH)
    if data is None and map_ref == base:
        data = load_json_at(repo, head, MAP_PATH)  # the change that introduces the map
    if data is None:
        raise DeltaError(f"no {MAP_PATH} at {map_ref} or {head}")
    m = Map(data)
    names = git(repo, "diff", "--name-only", "--no-renames", base, head).decode().split("\n")
    names = [n for n in names if n and (paths is None or n in paths)]
    report = {"schema": SCHEMA, "base": base, "head": head, "map_commit": data.get("source_commit"),
              "files": [], "cells": {}, "effects": set(), "kernel": False}
    cells = {}

    def add(cellset, why, effects):
        for c in cellset:
            e = cells.setdefault(c, {"why": set(), "effects": set()})
            e["why"].add(why)
            e["effects"].update(effects)

    for path in names:
        if not (path.endswith(".rs") or (path.startswith(CU_PREFIX + "cu/"))):
            report["files"].append({"path": path, "mode": "not-program"})
            continue
        b = scan(path, blob(repo, base, path))
        h = scan(path, blob(repo, head, path))
        touched = changed_lines(repo, base, head, path)
        entry = {"path": path, "items": []}
        ids = set(b) | set(h)
        for i in sorted(ids):
            bh, hh = b.get(i), h.get(i)
            if bh and hh and bh[0] == hh[0]:
                continue
            rec = hh or bh
            if rec[3]:
                entry["items"].append({"item": i, "change": "test-only"})
                continue
            kind = "modified" if bh and hh else ("added" if hh else "removed")
            known = i in m.items
            if known:
                at_map = m.items[i]["h"] == (bh[0] if bh else None)
                lines = {ln for ln in touched if bh and bh[1] <= ln <= bh[2]} if at_map else set()
                if at_map and kind == "modified":
                    cs, narrowed = m.narrowed(i, lines)
                else:
                    cs, narrowed = m.item_cells(i), False
                eff = set(m.items[i]["e"])
                src = "map-region" if narrowed else "map-item"
            else:
                cs = m.file_cells(path)
                src = "map-file" if cs is not None else "unknown-file"
                if cs is None:
                    cs = m.cells_of_set_all()
                eff = {"numeric", "speed", "memory", "policy"}
                narrowed = False
            if path.startswith(CU_PREFIX + "cu/") or path.endswith("_ffi.rs"):
                report["kernel"] = True
            entry["items"].append({"item": i, "change": kind, "source": src, "cells": len(cs), "effects": sorted(eff)})
            add(cs, i, eff)
            report["effects"] |= eff
        report["files"].append(entry)
    report["cells"] = cells
    report["doors"] = sorted(m.doors_hit)
    if fingerprints and cells:
        report["fingerprints"] = cell_fingerprints(m, tree_hashes(repo, head), set(cells))
    return report


def tests_for(cells_report):
    """(family, route, device) -> sorted test kinds."""
    out = {}
    kernel = cells_report["kernel"]
    for (f, r, d), e in cells_report["cells"].items():
        kinds = set()
        for eff in e["effects"]:
            kinds.update(EFFECT_TESTS.get(eff, ()))
        if "numeric" in e["effects"]:
            kinds.update(ROUTE_TESTS.get(r, ()))
        if kernel and d != "cpu":
            kinds.add("kernel-check")
        if kinds:
            out[(f, r, d)] = sorted(kinds)
    return out


def cell_fingerprints(m, item_hashes, cells):
    """Fingerprint of each cell: a digest over (item id, token hash) of every item whose map reach
    includes the cell, computed through the map's distinct reach sets so it stays cheap."""
    set_digest, set_cells = {}, {}
    by_set = {}
    for i, it in m.items.items():
        if set(it["e"]) <= {"observability", "none"}:
            continue  # verified output-neutral items do not invalidate a measurement
        by_set.setdefault(it["r"], []).append(i)
    for idx, ids in by_set.items():
        set_digest[idx] = fingerprint(item_hashes, ids)
        set_cells[idx] = m.cells_of_set(idx)
    out = {}
    for c in cells:
        h = hashlib.sha256()
        for idx in sorted(set_digest):
            if c in set_cells[idx]:
                h.update(f"{idx}:{set_digest[idx]}\n".encode())
        out[c] = h.hexdigest()[:24]
    return out


def tree_hashes(repo, ref):
    """{item id: token hash} for every Rust and CUDA item at ref."""
    out = {}
    listing = git(repo, "ls-tree", "-r", "--name-only", ref, "--", "crates").decode().splitlines()
    for path in listing:
        if path.endswith(".rs") or path.startswith(CU_PREFIX + "cu/"):
            for i, v in scan(path, blob(repo, ref, path)).items():
                out[i] = v[0]
    return out


def fingerprint(item_hashes, item_ids):
    h = hashlib.sha256()
    for i in sorted(item_ids):
        h.update(i.encode())
        h.update(b"=")
        h.update((item_hashes.get(i) or "-").encode())
        h.update(b"\n")
    return h.hexdigest()[:24]


GENERIC_ROUTES = ("plain", "prime", "graph", "chunked_prefill", "http_api")


# cheapest window first: the local desktop GPU, then the shared Sparks, then a granted workstation card
DEVICE_PREFERENCE = ("rtx5090", "gb10", "rtxpro6000", "h100", "b200", "sm89")


def plan(repo, ref, report, models=None, ledger=None, device_target=None, push_gated=None):
    """Minimal run set. Per (family, device): the fewest models (owner's own first) that cover the
    reached routes; each picked model runs the union of tests its covered routes need. CPU cells
    take the CPU suites. Cells no available model covers are listed as uncovered, never dropped.
    A (model, route, device, test) the ledger proves for the same cell fingerprint is skipped."""
    models = models if models is not None else (load_json_at(repo, ref, MODELS_PATH) or {"families": {}})
    ledger = ledger if ledger is not None else (load_json_at(repo, ref, LEDGER_PATH) or {"records": []})
    needs = tests_for(report)
    proven_keys = {(r["model"], r["route"], r["device"], r["test"], r.get("fingerprint")) for r in ledger.get("records", [])}
    fps = report.get("fingerprints", {})
    by_fd = {}
    cpu = set()
    for (fam, route, dev), kinds in needs.items():
        if dev == "cpu":
            cpu.add(fam)
            continue
        by_fd.setdefault((fam, dev), {})[route] = set(kinds)
    # tiers: with the gate's device -> target map, the PUSH tier is one device per (family, push-gated
    # target), preferring the cheapest window; everything else reached goes to that device's DAILY run
    tier_of = {}
    if device_target is not None:
        prefer = {d: i for i, d in enumerate(DEVICE_PREFERENCE)}
        by_ft = {}
        for (fam, dev) in by_fd:
            fams_models = [mm for mm in models.get("families", {}).get(fam, []) if dev in mm.get("devices", [])]
            t = device_target.get(dev)
            if t in (push_gated or ()) and fams_models:
                by_ft.setdefault((fam, t), []).append(dev)
        for (fam, t), devs in by_ft.items():
            chosen = min(devs, key=lambda d: prefer.get(d, 99))
            for d in devs:
                tier_of[(fam, d)] = "push" if d == chosen else "daily"
    runs, uncovered, proven = {}, [], []
    daily = {}
    for (fam, dev), routes in sorted(by_fd.items()):
        if device_target is not None and tier_of.get((fam, dev)) != "push":
            daily.setdefault(dev, set()).add(fam)
            continue
        cands = [mm for mm in models.get("families", {}).get(fam, []) if dev in mm.get("devices", [])]
        left = set(routes)
        while left:
            def covers(mm):
                return {r for r in left if r in mm.get("routes", ()) or r in GENERIC_ROUTES}
            best = max(cands, key=lambda mm: (len(covers(mm)), mm.get("class") == "own", mm["id"]), default=None)
            got = covers(best) if best else set()
            if not got:
                for r in sorted(left):
                    uncovered.append({"family": fam, "route": r, "device": dev, "tests": sorted(routes[r])})
                break
            slot = runs.setdefault(dev, {}).setdefault(best["id"], {"family": fam, "routes": set(), "tests": set()})
            for r in got:
                for t in routes[r]:
                    fp = fps.get((fam, r, dev))
                    if fp and (best["id"], r, dev, t, fp) in proven_keys:
                        proven.append({"model": best["id"], "route": r, "device": dev, "test": t})
                        continue
                    slot["routes"].add(r)
                    slot["tests"].add(t)
            left -= got
            cands = [mm for mm in cands if mm is not best]
    out = {d: {m: {"family": v["family"], "routes": sorted(v["routes"]), "tests": sorted(v["tests"])}
               for m, v in ms.items() if v["tests"]} for d, ms in runs.items()}
    return {"runs": {d: ms for d, ms in out.items() if ms}, "cpu_families": sorted(cpu), "uncovered": uncovered,
            "proven": proven, "daily": {d: sorted(f) for d, f in sorted(daily.items())}}


def summarize(report):
    fams, routes, devs = set(), set(), set()
    for (f, r, d) in report["cells"]:
        fams.add(f)
        routes.add(r)
        devs.add(d)
    return {"cells": len(report["cells"]), "families": sorted(fams), "routes": sorted(routes), "devices": sorted(devs),
            "effects": sorted(report["effects"]), "kernel": report["kernel"]}


def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--repo", default=".")
    ap.add_argument("--base", default="origin/main")
    ap.add_argument("--head", default="HEAD")
    ap.add_argument("--map-ref", default=None)
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args(argv)
    try:
        rep = delta(a.repo, a.base, a.head, map_ref=a.map_ref, fingerprints=True)
    except DeltaError as error:
        print(f"impact map: {error}", file=sys.stderr)
        return 2
    dev_target = pushed = None
    try:  # the gate's device -> target map and push-gated targets, for the push/daily tiers
        sys.path.insert(0, str(HERE.parent))
        import change_impact as ci
        import gate as g
        arch = ci.arch_table_at(a.repo, a.head)
        rules = ci.rules_at(a.repo, a.base, arch)
        dev_target = g.device_targets(rules, arch)
        pushed = {t for t, r in rules.get("target", {}).items() if r.get("push_gate")}
    except Exception:  # noqa: BLE001 - no rules at the base: one flat plan
        pass
    pl = plan(a.repo, a.map_ref or a.base, rep, device_target=dev_target, push_gated=pushed)
    if a.json:
        print(json.dumps({"summary": summarize(rep), "plan": pl}, indent=1, default=sorted))
        return 0
    s = summarize(rep)
    print(f"impact: {s['cells']} cells; families={','.join(s['families']) or '-'} routes={','.join(s['routes']) or '-'} "
          f"devices={','.join(s['devices']) or '-'} effects={','.join(s['effects']) or '-'}{' kernel' if s['kernel'] else ''}")
    for dev, ms in sorted(pl["runs"].items()):
        for model, v in sorted(ms.items()):
            print(f"  run on {dev}: {model} ({v['family']}): routes={','.join(v['routes'])} tests={','.join(v['tests'])}")
    if pl["cpu_families"]:
        print("  cpu suites (cargo test of the touched crates) cover: " + ",".join(pl["cpu_families"]))
    if pl.get("daily"):
        print("  daily run (per device, not at push): " + "; ".join(f"{d}: {','.join(f)}" for d, f in pl["daily"].items()))
    unc = {}
    for u in pl["uncovered"]:
        unc.setdefault((u["family"], u["device"]), set()).add(u["route"])
    for (fam, dev), routes in sorted(unc.items()):
        print(f"  not covered by a measured {fam} model on {dev}: {len(routes)} route(s) ({','.join(sorted(routes)[:6])}{',...' if len(routes) > 6 else ''})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
