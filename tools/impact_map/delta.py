class DeltaError(ValueError):
    pass


def crate_dir(path):
    m = re.match(r"crates/([^/]+)/", path)
    return m.group(1) if m else None


def battery_linked(repo, base, head):
    """Crates linked into the battery binaries at base or head (tools/change_impact.py
    link_closure), or None when the manifests cannot say: every item then counts as linked."""
    try:
        sys.path.insert(0, str(HERE.parent))
        import change_impact as ci
        return ci.battery_linked(repo, base, head)
    except Exception:  # noqa: BLE001 - unknown means linked, which only widens
        return None


def is_linked(path, linked):
    d = crate_dir(path)
    return linked is None or d is None or d in linked


def git(repo, *args, check=True, inp=None):
    r = subprocess.run(["git", "-C", str(repo), "-c", "core.quotePath=false", *args], capture_output=True, input=inp)
    if check and r.returncode != 0:
        raise DeltaError("git " + " ".join(args[:3]) + ": " + r.stderr.decode(errors="replace").strip())
    return r.stdout


def blob(repo, ref, path):
    r = subprocess.run(["git", "-C", str(repo), "show", f"{ref}:{path}"], capture_output=True)
    return r.stdout.decode("utf-8", "surrogateescape") if r.returncode == 0 else None


def load_json_at(repo, ref, path):
    text = blob(repo, ref, path)
    return None if text is None else json.loads(text)


SCANNED = (".rs",)
CU_SCANNED = (".cu", ".cuh", ".h")
# inputs whose change since the map moves per-arch liveness or cfg flags for every item
ARCH_INPUTS = re.compile(r"^crates/memra-engine/(build\.rs|src/cuda_arch\.rs)$")


def scannable(path):
    return path.endswith(SCANNED) or (path.startswith(CU_PREFIX + "cu/") and path.endswith(CU_SCANNED))


def scan(path, text):
    """Items of one file keyed by stable id: {id: (hash, line_start, line_end, test, kind, lhash, idents)}.
    The synthetic `<outside>` item holds every token outside an item, so no edit is invisible."""
    if text is None:
        return {}
    if path.endswith(".rs"):
        recs = rust_items.scan(path, text)
    elif path.endswith(CU_SCANNED) and path.startswith(CU_PREFIX):
        recs = []
        for r in cu_items.scan(path[len(CU_PREFIX):], text):
            if r["kind"] == "pp":
                h = hashlib.sha256(r["text"].encode("utf-8", "surrogatepass")).hexdigest()[:20]
                r = dict(r, hash=h, lhash=h)
            r["id"] = CU_PREFIX + r["id"]
            recs.append(r)
    else:
        return {}
    return {r["id"]: (r["hash"], r["line_start"], r["line_end"], r.get("test", False), r["kind"],
                      r.get("lhash"), frozenset(r.get("idents", ()))) for r in recs}


def changed_lines(repo, base, head, path):
    """Base-side line numbers touched by the diff (deleted or next to an insertion)."""
    out = git(repo, "diff", "-U0", "--no-color", base, head, "--", path).decode(errors="replace")
    lines = set()
    for m in re.finditer(r"^@@ -(\d+)(?:,(\d+))? \+\d+(?:,\d+)? @@", out, re.M):
        start, n = int(m.group(1)), int(m.group(2) or 1)
        lines.update(range(start, start + n) if n else (start, start + 1))
    return lines


def changed_paths(repo, base, head):
    out = git(repo, "diff", "--name-only", "-z", "--no-renames", base, head).decode("utf-8", "surrogateescape")
    return [n for n in out.split("\0") if n]


class Map:
    def __init__(self, data):
        if data.get("schema") != "memra-impact-map-v1":
            raise DeltaError(f"unknown map schema {data.get('schema')}")
        for key in ("items", "reach_sets", "vocab", "source_commit"):
            if key not in data:
                raise DeltaError(f"impact map is missing {key}")
        self.data = data
        self.items = data["items"]
        self.sets = data["reach_sets"]
        self.vocab = data["vocab"]
        self.by_file = {}
        self._set_cells = {}
        for i, it in self.items.items():
            self.by_file.setdefault(it["f"], []).append(i)
            if not (0 <= it["r"] < len(self.sets)):
                raise DeltaError(f"impact map item {i} names reach set {it['r']}")
        self.doors_hit = set()
        self.regions = {}
        for rg in data.get("regions", []):
            self.regions.setdefault(rg["file"], []).append(rg)

    def cells_of_set(self, idx):
        if idx not in self._set_cells:
            s = self.sets[idx]
            if s == "*":
                self._set_cells[idx] = frozenset(self.cells_of_set_all())
            else:
                self._set_cells[idx] = frozenset((f, r, d) for f, routes in s.items() for r, devs in routes.items() for d in devs)
        return set(self._set_cells[idx])

    def item_cells(self, item_id):
        it = self.items.get(item_id)
        if it is None:
            return None
        out = self.cells_of_set(it["r"])
        if it.get("x") is not None:  # a writer of process-global state: its change reaches every reader
            out |= self.cells_of_set(it["x"])
        return out

    def file_cells(self, path):
        ids = self.by_file.get(path)
        if not ids:
            return None
        out = set()
        for i in ids:
            out |= self.item_cells(i)
        return out

    def all_cells(self):
        return self.cells_of_set_all()

    def cells_of_set_all(self):
        v = self.vocab
        return {(f, r, d) for f in v["families"] for r in v["routes"] for d in v["devices"]}

    def region_cells(self, rg):
        v = self.vocab
        if rg.get("door") and rg["door"].get("default_reached") is False:
            return set()

        def pick(vals, universe):
            if not vals or "*" in vals or any(x not in universe for x in vals):
                return list(universe)  # an unknown label widens, as in assemble.py
            return list(vals)
        return {(f, r, d) for f in pick(rg.get("families"), v["families"]) for r in pick(rg.get("routes"), v["routes"])
                for d in pick(rg.get("devices"), v["devices"])}

    def narrowed(self, item_id, lines):
        """Cells for a change at `lines` (base numbering) inside an item whose base layout equals the
        map's (same token layout hash and start line), so the map's region lines are this tree's.
        Narrows only when every touched line sits strictly inside a labelled non-'none' region."""
        it = self.items[item_id]
        full = self.item_cells(item_id)
        regs = [rg for rg in self.regions.get(it["f"], []) if rg.get("kind") != "none"
                and it["a"] <= rg["a"] <= it["b"]]
        if not lines or not regs:
            return full, False
        out = set()
        for ln in lines:
            best = None
            for rg in regs:
                # strictly after the region's first line: the first line usually carries the
                # branch condition, and a changed condition moves every arm, not just this one
                if rg["a"] < ln <= rg["b"] and (best is None or rg["b"] - rg["a"] < best["b"] - best["a"]):
                    best = rg
            if best is None:
                return full, False
            if best.get("door") and best["door"].get("default_reached") is False:
                self.doors_hit.add(best["door"].get("env", "?"))
            out |= self.region_cells(best)
        if it.get("x") is not None:
            out |= self.cells_of_set(it["x"])
        return out & full, True


_DRIFT = {}


def map_drift(repo, m, base):
    key = (str(repo), id(m), base)
    if key not in _DRIFT:
        _DRIFT[key] = _map_drift(repo, m, base)
    return _DRIFT[key]


def _map_drift(repo, m, base):
    """What changed between the map commit and the base: the identifiers of every changed or added
    item (a new caller of an item the map placed before it existed), and whether the arch table
    moved. -> (idents -> cells they add, arch_moved)."""
    mc = m.data.get("source_commit")
    if not mc or git(repo, "cat-file", "-t", mc, check=False).strip() != b"commit":
        return None, True  # the map's commit is unknown here: nothing narrows
    if mc == base:
        return {}, False
    if subprocess.run(["git", "-C", str(repo), "merge-base", "--is-ancestor", mc, base]).returncode != 0:
        return None, True  # the map is not an ancestor of the base: nothing narrows
    callers = {}
    arch_moved = False
    for path in changed_paths(repo, mc, base):
        if ARCH_INPUTS.match(path) or path in ("Cargo.toml", "rust-toolchain.toml"):
            arch_moved = True
        if not scannable(path):
            continue
        a = scan(path, blob(repo, mc, path))
        b = scan(path, blob(repo, base, path))
        for i, v in b.items():
            if i in a and a[i][0] == v[0]:
                continue
            cs = m.item_cells(i) if i in m.items else (m.file_cells(path) or m.cells_of_set_all())
            for ident in v[6]:
                callers.setdefault(ident, set()).update(cs)
    return callers, arch_moved


def delta(repo, base, head, *, map_ref=None, paths=None, map_data=None, map_obj=None, fingerprints=False,
          whatif=False):
    """The cells base..head can reach. map_ref defaults to base (the rules in force). whatif applies
    a map to a diff it was not built before (history replays): it skips the ancestry and drift check
    the push gate needs, so it answers "what would this map pick", not a push decision."""
    if map_obj is not None:
        m = map_obj
    else:
        map_ref = map_ref or base
        data = map_data if map_data is not None else load_json_at(repo, map_ref, MAP_PATH)
        if data is None and map_ref == base:
            data = load_json_at(repo, head, MAP_PATH)  # the change that introduces the map
        if data is None:
            raise DeltaError(f"no {MAP_PATH} at {map_ref} or {head}")
        m = Map(data)
    names = [n for n in changed_paths(repo, base, head) if paths is None or n in paths]
    drift, arch_moved = ({}, False) if whatif else map_drift(repo, m, base)
    linked = battery_linked(repo, base, head)
    report = {"schema": SCHEMA, "base": base, "head": head, "map_commit": m.data.get("source_commit"),
              "files": [], "cells": {}, "effects": set(), "kernel": False, "arch_moved": arch_moved,
              "map_stale_base": drift is None}
    cells = {}

    def add(cellset, why, effects, item_linked=True):
        for c in cellset:
            e = cells.setdefault(c, {"why": set(), "effects": set(), "linked": False})
            e["why"].add(why)
            e["effects"].update(effects)
            e["linked"] |= item_linked

    all_eff = {"numeric", "speed", "memory", "policy"}
    for path in names:
        program = path.endswith(".rs") or path.startswith(CU_PREFIX + "cu/")
        if not program:
            report["files"].append({"path": path, "mode": "not-program"})
            continue
        if not scannable(path):
            # a file under cu/ the scanner does not read (.inl, .hpp, binary): nothing to place
            report["files"].append({"path": path, "mode": "unscannable"})
            add(m.cells_of_set_all(), path, all_eff)
            report["kernel"] = True
            report["effects"] |= all_eff
            continue
        b = scan(path, blob(repo, base, path))
        h = scan(path, blob(repo, head, path))
        touched = changed_lines(repo, base, head, path)
        entry = {"path": path, "items": []}
        for i in sorted(set(b) | set(h)):
            bh, hh = b.get(i), h.get(i)
            if bh and hh and bh[0] == hh[0]:
                continue
            # test-only only when every present side is a test item (a production item moved into
            # cfg(test) is a production removal)
            if (not bh or bh[3]) and (not hh or hh[3]):
                entry["items"].append({"item": i, "change": "test-only"})
                continue
            kind = "modified" if bh and hh else ("added" if hh else "removed")
            # an added item is new code even if its id is old; `<outside>` is never placed
            known = i in m.items and kind != "added" and not i.endswith("::<outside>")
            narrowed = False
            if known:
                mi = m.items[i]
                at_map = (drift is not None and mi["h"] == (bh[0] if bh else None)
                          and mi.get("l") is not None and mi.get("l") == (bh[5] if bh else None) and mi["a"] == bh[1])
                lines = {ln for ln in touched if bh and bh[1] <= ln <= bh[2]} if at_map else set()
                if at_map and kind == "modified":
                    cs, narrowed = m.narrowed(i, lines)
                else:
                    cs = m.item_cells(i)
                eff = set(mi["e"])
                src = "map-region" if narrowed else "map-item"
                if not cs:
                    src = "map-empty"  # placed nowhere by default (a build-time door): not narrowed
                    cs = m.file_cells(path) or m.cells_of_set_all()
                    eff = all_eff
            else:
                cs = m.file_cells(path)
                src = "map-file" if cs is not None else "unknown-file"
                if cs is None:
                    cs = m.cells_of_set_all()
                eff = all_eff
            if drift is None:
                src = "map-not-ancestor"
                cs = m.cells_of_set_all()
            else:
                name = i.split("::")[-1].split("#")[0]
                if name in drift:  # a caller added or changed since the map was built
                    cs = cs | drift[name]
                    if src in ("map-item", "map-region"):
                        src += "+drift"
            if path.startswith(CU_PREFIX + "cu/") or path.endswith("_ffi.rs"):
                report["kernel"] = True
            item_linked = is_linked(path, linked)
            if not item_linked and eff - {"observability", "none"}:
                eff = {"served"}
            entry["items"].append({"item": i, "change": kind, "source": src, "cells": len(cs), "effects": sorted(eff),
                                   "linked": item_linked})
            add(cs, i, eff, item_linked)
            report["effects"] |= eff
        report["files"].append(entry)
    report["cells"] = cells
    report["doors"] = sorted(m.doors_hit)
    if fingerprints and cells:
        hashes = tree_hashes(repo, head)
        report["fingerprints"] = cell_fingerprints(m, hashes, set(cells))
        report["fingerprints_engine"] = cell_fingerprints(m, hashes, set(cells), linked=linked)
    return report


def tests_for(cells_report):
    """(family, route, device) -> sorted test kinds."""
    out = {}
    kernel = cells_report["kernel"]
    for (f, r, d), e in cells_report["cells"].items():
        kinds = set()
        for eff in e["effects"]:
            kinds.update(EFFECT_TESTS.get(eff, ()))
        if "numeric" in e["effects"]:
            kinds.update(ROUTE_TESTS.get(r, ()))
        if kernel and d != "cpu" and e.get("linked", True):
            kinds.add("kernel-check")
        if kinds:
            out[(f, r, d)] = sorted(kinds)
    return out


def cell_fingerprints(m, item_hashes, cells, linked=None):
    """Fingerprint of each cell: a digest over (item id, token hash) of every item whose map reach
    includes the cell, computed through the map's distinct reach sets so it stays cheap. With
    `linked` (crate directory names), only items in those crates count: the fingerprint of a test
    that runs a memra-engine binary (ENGINE_TESTS), which no other crate's code can move."""
    set_digest, set_cells = {}, {}
    by_set = {}
    for i, it in m.items.items():
        if set(it["e"]) <= {"observability", "none"}:
            continue  # verified output-neutral items do not invalidate a measurement
        if linked is not None and not is_linked(it["f"], linked):
            continue
        by_set.setdefault((it["r"], it.get("x")), []).append(i)
    for idx, ids in by_set.items():
        set_digest[idx] = fingerprint(item_hashes, ids)
        cs = m.cells_of_set(idx[0])
        if idx[1] is not None:
            cs |= m.cells_of_set(idx[1])
        set_cells[idx] = cs
    out = {}
    for c in cells:
        h = hashlib.sha256()
        for idx in sorted(set_digest, key=lambda k: (k[0], -1 if k[1] is None else k[1])):
            if c in set_cells[idx]:
                h.update(f"{idx}:{set_digest[idx]}\n".encode())
        out[c] = h.hexdigest()[:24]
    return out


def tree_hashes(repo, ref):
    """{item id: token hash} for every Rust and CUDA item at ref."""
    out = {}
    listing = git(repo, "ls-tree", "-r", "--name-only", ref, "--", "crates").decode().splitlines()
    for path in listing:
        if path.endswith(".rs") or path.startswith(CU_PREFIX + "cu/"):
            for i, v in scan(path, blob(repo, ref, path)).items():
                out[i] = v[0]
    return out


def fingerprint(item_hashes, item_ids):
    h = hashlib.sha256()
    for i in sorted(item_ids):
        h.update(i.encode())
        h.update(b"=")
        h.update((item_hashes.get(i) or "-").encode())
        h.update(b"\n")
    return h.hexdigest()[:24]


GENERIC_ROUTES = ("plain", "prime", "graph", "chunked_prefill", "http_api")


# cheapest window first: the local desktop GPU, then the shared Sparks, then a granted workstation card
DEVICE_PREFERENCE = ("rtx5090", "gb10", "rtxpro6000", "h100", "b200", "sm89")


def plan(repo, ref, report, models=None, ledger=None, device_target=None, push_gated=None):
    """Minimal run set. Per (family, device): the fewest models (owner's own first) that cover the
    reached routes; each picked model runs the union of tests its covered routes need. CPU cells
    take the CPU suites. Cells no available model covers are listed as uncovered, never dropped.
    A (model, route, device, test) the ledger proves for the same cell fingerprint is skipped."""
    models = models if models is not None else (load_json_at(repo, ref, MODELS_PATH) or {"families": {}})
    ledger = ledger if ledger is not None else (load_json_at(repo, ref, LEDGER_PATH) or {"records": []})
    needs = tests_for(report)
    proven_keys = {(r["model"], r["route"], r["device"], r["test"], r.get("fingerprint")) for r in ledger.get("records", [])}
    fps = report.get("fingerprints", {})
    fps_engine = report.get("fingerprints_engine", fps)
    prefer = {d: i for i, d in enumerate(DEVICE_PREFERENCE)}
    # a cell reached only by code outside the battery binaries runs no device-specific code of its
    # own: one device proves it. Fold its tests onto the family's cheapest device with a model.
    free = {}
    for c in list(needs):
        f, r, d = c
        if d != "cpu" and not report["cells"].get(c, {}).get("linked", True):
            free.setdefault((f, r), {})[d] = needs.pop(c)
    for (f, r), per_dev in free.items():
        with_model = [d for d in per_dev if any(d in mm.get("devices", []) for mm in models.get("families", {}).get(f, []))]
        keep = min(with_model or list(per_dev), key=lambda d: (prefer.get(d, 99), d))
        kinds = set(needs.get((f, r, keep), ())).union(*per_dev.values())
        needs[(f, r, keep)] = sorted(kinds)
    by_fd = {}
    cpu = set()
    for (fam, route, dev), kinds in needs.items():
        if dev == "cpu":
            cpu.add(fam)
            continue
        by_fd.setdefault((fam, dev), {})[route] = set(kinds)
    # tiers: with the gate's device -> target map, the PUSH tier is one device per (family, push-gated
    # target), preferring the cheapest window; everything else reached goes to that device's DAILY run
    tier_of = {}
    if device_target is not None:
        by_ft = {}
        for (fam, dev) in by_fd:
            fams_models = [mm for mm in models.get("families", {}).get(fam, []) if dev in mm.get("devices", [])]
            t = device_target.get(dev)
            if t in (push_gated or ()) and fams_models:
                by_ft.setdefault((fam, t), []).append(dev)
        for (fam, t), devs in by_ft.items():
            chosen = min(devs, key=lambda d: prefer.get(d, 99))
            for d in devs:
                tier_of[(fam, d)] = "push" if d == chosen else "daily"
    runs, uncovered, proven = {}, [], []
    daily = {}
    for (fam, dev), routes in sorted(by_fd.items()):
        if device_target is not None and tier_of.get((fam, dev)) != "push":
            daily.setdefault(dev, set()).add(fam)
            continue
        cands = [mm for mm in models.get("families", {}).get(fam, []) if dev in mm.get("devices", [])]
        left = set(routes)
        while left:
            def covers(mm):
                return {r for r in left if r in mm.get("routes", ()) or r in GENERIC_ROUTES}
            best = max(cands, key=lambda mm: (len(covers(mm)), mm.get("class") == "own", mm["id"]), default=None)
            got = covers(best) if best else set()
            if not got:
                for r in sorted(left):
                    uncovered.append({"family": fam, "route": r, "device": dev, "tests": sorted(routes[r])})
                break
            slot = runs.setdefault(dev, {}).setdefault(best["id"], {"family": fam, "routes": set(), "tests": set()})
            for r in got:
                for t in routes[r]:
                    fp = (fps_engine if t in ENGINE_TESTS else fps).get((fam, r, dev))
                    if fp and (best["id"], r, dev, t, fp) in proven_keys:
                        proven.append({"model": best["id"], "route": r, "device": dev, "test": t})
                        continue
                    slot["routes"].add(r)
                    slot["tests"].add(t)
            left -= got
            cands = [mm for mm in cands if mm is not best]
    out = {d: {m: {"family": v["family"], "routes": sorted(v["routes"]), "tests": sorted(v["tests"])}
               for m, v in ms.items() if v["tests"]} for d, ms in runs.items()}
    return {"runs": {d: ms for d, ms in out.items() if ms}, "cpu_families": sorted(cpu), "uncovered": uncovered,
            "proven": proven, "daily": {d: sorted(f) for d, f in sorted(daily.items())}}


def summarize(report):
    fams, routes, devs = set(), set(), set()
    for (f, r, d) in report["cells"]:
        fams.add(f)
        routes.add(r)
        devs.add(d)
    return {"cells": len(report["cells"]), "families": sorted(fams), "routes": sorted(routes), "devices": sorted(devs),
            "effects": sorted(report["effects"]), "kernel": report["kernel"]}


