/// The one configuration name: a file path, opened for append at boot.
pub(crate) const ENV: &str = "MEMRA_REQUEST_LOG";
/// Version of the line schema, written as `"v"` on every line.
pub(crate) const SCHEMA_VERSION: u32 = 1;
/// Lines the writer may lag behind. The queue only has to ride out a slow disk: at 100 requests
/// per second this is about 40 s of stall before a line drops.
const QUEUE_LINES: usize = 4096;
/// Bytes the queued lines may pin, prompt-id copies included (4 bytes per prompt token): a stalled
/// disk costs at most this much RAM before lines drop.
const QUEUE_BYTES: usize = 64 << 20;
/// Charged per line on top of its prompt ids and tool-call text: the record itself.
const LINE_BYTES: usize = 1024;

/// How a request ended. Exactly one per line.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum EndReason {
    /// The model stopped: an end-of-turn token, a stop string or id, or a tool call.
    Stop,
    /// The generation bound was reached: `max_tokens` or the context.
    Length,
    /// A refusal or a failure: any HTTP error status, an engine error, or a worker that closed
    /// the stream without a terminal event.
    Error,
    /// The consumer let go before a terminal event: the client left, or a background job was
    /// cancelled.
    Cancelled,
    /// The request's deadline (`timeout_ms`) cut it, before or after its first token.
    Deadline,
}

impl EndReason {
    pub(crate) fn as_str(self) -> &'static str {
        match self {
            Self::Stop => "stop",
            Self::Length => "length",
            Self::Error => "error",
            Self::Cancelled => "cancelled",
            Self::Deadline => "deadline",
        }
    }
}

/// Where the explicit session identity came from (the `affinity_key` priority order).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum SessionSource {
    SessionId,
    User,
    Header,
}

impl SessionSource {
    pub(crate) fn as_str(self) -> &'static str {
        match self {
            Self::SessionId => "session_id",
            Self::User => "user",
            Self::Header => "x-session-id",
        }
    }
}

/// The tokenizer's turn-marker predicate, the boundary test of the implicit affinity tier.
pub(crate) trait ControlTokens: Send + Sync {
    fn is_control(&self, id: u32) -> bool;
}

impl ControlTokens for memra_tokenizer::Tokenizer {
    fn is_control(&self, id: u32) -> bool {
        self.token_is_control(id)
    }
}

/// The prompt as the worker fed it, handed to the writer thread for hashing.
pub(crate) struct PromptTap {
    ids: Vec<u32>,
    controls: Arc<dyn ControlTokens>,
}

/// The worker-side half of a request's entry: the event sender carries it, the worker fills it
/// once after tokenizing.
#[derive(Clone, Default)]
pub(crate) struct PromptSlot(Arc<Mutex<Option<PromptTap>>>);

impl PromptSlot {
    /// First fill wins: a re-prepared request (a deferred admission) does not copy again.
    pub(crate) fn fill<C: ControlTokens + 'static>(&self, ids: &[u32], controls: &Arc<C>) {
        let mut slot = self.0.lock().unwrap_or_else(|e| e.into_inner());
        if slot.is_none() {
            let controls: Arc<dyn ControlTokens> = controls.clone();
            *slot = Some(PromptTap {
                ids: ids.to_vec(),
                controls,
            });
        }
    }

    fn take(&self) -> Option<PromptTap> {
        self.0.lock().unwrap_or_else(|e| e.into_inner()).take()
    }
}

impl std::fmt::Debug for PromptSlot {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("PromptSlot")
    }
}

/// Everything known about one request, filled by the observers and rendered by the writer.
#[derive(Default)]
struct Rec {
    route: &'static str,
    arrival: Option<SystemTime>,
    request_id: Option<String>,
    model: Option<String>,
    stream: bool,
    status: Option<u16>,
    session: Option<(String, SessionSource)>,
    first_token: Option<SystemTime>,
    http_end: Option<SystemTime>,
    generation_end: Option<SystemTime>,
    dropped_at: Option<SystemTime>,
    reached_worker: bool,
    prompt_tokens: Option<u64>,
    cached_tokens: Option<u64>,
    done_tokens: Option<u64>,
    seen_tokens: u64,
    stop_reason: Option<String>,
    engine_error: bool,
    worker_closed: bool,
    mark: Option<EndReason>,
    /// `None` on a route that does not parse tool calls (`/v1/completions` returns raw text).
    tool_calls: Option<Vec<(String, String)>>,
}

impl Rec {
    fn end_reason(&self) -> EndReason {
        if let Some(mark) = self.mark {
            return mark;
        }
        if let Some(stop) = self.stop_reason.as_deref() {
            return match crate::stop_reason_to_finish(stop) {
                "length" => EndReason::Length,
                _ => EndReason::Stop,
            };
        }
        if self.engine_error || self.worker_closed {
            return EndReason::Error;
        }
        match self.status {
            // No response head: the client left while the handler was still working.
            None => EndReason::Cancelled,
            Some(408) => EndReason::Deadline,
            Some(status) if status >= 400 => EndReason::Error,
            // A success head whose generation stopped without a terminal event: the stream's
            // client hung up, or a background job was cancelled.
            Some(_) => EndReason::Cancelled,
        }
    }
}

struct Counters {
    queued_bytes: AtomicUsize,
    accepted: AtomicU64,
    written: AtomicU64,
    dropped_queue_full: AtomicU64,
    dropped_write_error: AtomicU64,
    /// Lines the writer has finished (written or failed), for [`Sink::wait_for`].
    done: Mutex<u64>,
    done_cv: Condvar,
}

/// The bounded queue and its writer thread. One per configured path.
pub(crate) struct Sink {
    tx: SyncSender<Box<Pending>>,
    counters: Arc<Counters>,
}

struct Pending {
    rec: Rec,
    prompt: Option<PromptTap>,
    bytes: usize,
}

impl Sink {
    /// Open `path` for append (created 0640 when absent) and start the writer thread.
    pub(crate) fn open(path: &Path) -> std::io::Result<Arc<Self>> {
        use std::os::unix::fs::OpenOptionsExt as _;
        let file = std::fs::OpenOptions::new()
            .create(true)
            .append(true)
            .mode(0o640)
            .open(path)?;
        let (tx, rx) = std::sync::mpsc::sync_channel(QUEUE_LINES);
        let counters = Arc::new(Counters {
            queued_bytes: AtomicUsize::new(0),
            accepted: AtomicU64::new(0),
            written: AtomicU64::new(0),
            dropped_queue_full: AtomicU64::new(0),
            dropped_write_error: AtomicU64::new(0),
            done: Mutex::new(0),
            done_cv: Condvar::new(),
        });
        let writer = counters.clone();
        let shown = path.display().to_string();
        std::thread::Builder::new()
            .name("memra-request-log".into())
            .spawn(move || write_loop(rx, file, writer, shown))?;
        Ok(Arc::new(Self { tx, counters }))
    }

    /// Never blocks: a line that does not fit the queue is dropped and counted.
    fn submit(&self, rec: Rec, prompt: Option<PromptTap>) {
        let bytes = LINE_BYTES
            + prompt.as_ref().map_or(0, |p| p.ids.len() * 4)
            + rec
                .tool_calls
                .iter()
                .flatten()
                .map(|(name, args)| name.len() + args.len())
                .sum::<usize>();
        let c = &self.counters;
        if c.queued_bytes.fetch_add(bytes, Ordering::AcqRel) + bytes > QUEUE_BYTES {
            c.queued_bytes.fetch_sub(bytes, Ordering::AcqRel);
            c.dropped_queue_full.fetch_add(1, Ordering::Relaxed);
            return;
        }
        match self.tx.try_send(Box::new(Pending { rec, prompt, bytes })) {
            Ok(()) => {
                c.accepted.fetch_add(1, Ordering::AcqRel);
            }
            Err(_) => {
                c.queued_bytes.fetch_sub(bytes, Ordering::AcqRel);
                c.dropped_queue_full.fetch_add(1, Ordering::Relaxed);
            }
        }
    }

    /// Wait until the writer has finished `lines` lines in total, or `timeout` passes. Returns
    /// whether it got there. Shutdown and tests only.
    pub(crate) fn wait_for(&self, lines: u64, timeout: Duration) -> bool {
        let done = self.counters.done.lock().unwrap_or_else(|e| e.into_inner());
        let (done, _) = self
            .counters
            .done_cv
            .wait_timeout_while(done, timeout, |done| *done < lines)
            .unwrap_or_else(|e| e.into_inner());
        *done >= lines
    }

    /// Wait until every line accepted so far is finished. Shutdown and tests only.
    pub(crate) fn drain(&self, timeout: Duration) -> bool {
        self.wait_for(self.counters.accepted.load(Ordering::Acquire), timeout)
    }

    #[cfg(test)]
    pub(crate) fn dropped(&self) -> u64 {
        self.counters.dropped_queue_full.load(Ordering::Relaxed)
            + self.counters.dropped_write_error.load(Ordering::Relaxed)
    }
}

fn write_loop(rx: Receiver<Box<Pending>>, mut file: std::fs::File, c: Arc<Counters>, path: String) {
    let mut warned = false;
    while let Ok(pending) = rx.recv() {
        let bytes = pending.bytes;
        let mut line = render(*pending);
        line.push('\n');
        // One O_APPEND write per line: a line is never interleaved with another writer's, and a
        // failed write is counted exactly.
        match file.write_all(line.as_bytes()) {
            Ok(()) => {
                c.written.fetch_add(1, Ordering::Relaxed);
            }
            Err(err) => {
                c.dropped_write_error.fetch_add(1, Ordering::Relaxed);
                if !warned {
                    warned = true;
                    eprintln!(
                        "[request-log] ERROR: write to {path} failed: {err}; dropping lines \
                         (counted in memra_request_log_lines_total)"
                    );
                }
            }
        }
        c.queued_bytes.fetch_sub(bytes, Ordering::AcqRel);
        let mut done = c.done.lock().unwrap_or_else(|e| e.into_inner());
        *done += 1;
        c.done_cv.notify_all();
    }
}

#[derive(Serialize)]
struct Line<'a> {
    v: u32,
    request_id: Option<&'a str>,
    route: &'a str,
    model: Option<&'a str>,
    stream: bool,
    session_key: Option<String>,
    session_key_source: Option<&'static str>,
    t_arrival: f64,
    t_first_token: Option<f64>,
    t_end: f64,
    end_reason: &'static str,
    http_status: u16,
    prompt_tokens: Option<u64>,
    cached_tokens: Option<u64>,
    generated_tokens: Option<u64>,
    tool_calls: Option<Vec<ToolCallLine<'a>>>,
    prompt_sha256: Option<String>,
}

#[derive(Serialize)]
struct ToolCallLine<'a> {
    name: &'a str,
    arguments_sha256: String,
}

fn sha256_hex(bytes: &[u8]) -> String {
    let digest = Sha256::digest(bytes);
    let mut out = String::with_capacity(64);
    for b in digest {
        out.push_str(&format!("{b:02x}"));
    }
    out
}

/// Prompt ids hash as their little-endian u32 bytes, in order.
fn ids_sha256(ids: &[u32]) -> String {
    let mut h = Sha256::new();
    for id in ids {
        h.update(id.to_le_bytes());
    }
    let mut out = String::with_capacity(64);
    for b in h.finalize() {
        out.push_str(&format!("{b:02x}"));
    }
    out
}

fn epoch_s(t: SystemTime) -> f64 {
    t.duration_since(UNIX_EPOCH)
        .map(|d| d.as_micros() as f64 / 1e6)
        .unwrap_or(0.0)
}

fn render(p: Pending) -> String {
    let Pending { rec, prompt, .. } = p;
    // Explicit identity first (hashed: a client-chosen id, not ours to republish); otherwise the
    // implicit affinity tier's key over the prompt the worker fed.
    let (session_key, session_key_source) = match &rec.session {
        Some((key, source)) => (Some(sha256_hex(key.as_bytes())), Some(source.as_str())),
        None => match prompt.as_ref().and_then(|p| {
            crate::worker::implicit_affinity_key(&p.ids, &|t| p.controls.is_control(t))
        }) {
            Some(chain) => {
                let bytes: Vec<u8> = chain.iter().flat_map(|h| h.to_le_bytes()).collect();
                (Some(sha256_hex(&bytes)), Some("fingerprint"))
            }
            None => (None, None),
        },
    };
    let arrival = rec.arrival.unwrap_or(UNIX_EPOCH);
    let end = rec
        .http_end
        .into_iter()
        .chain(rec.generation_end)
        .max()
        .or(rec.dropped_at)
        .unwrap_or(arrival);
    let generated_tokens = rec
        .done_tokens
        .or(rec.reached_worker.then_some(rec.seen_tokens));
    let tool_calls = rec.tool_calls.as_ref().map(|calls| {
        calls
            .iter()
            .map(|(name, args)| ToolCallLine {
                name,
                arguments_sha256: sha256_hex(args.as_bytes()),
            })
            .collect()
    });
    let line = Line {
        v: SCHEMA_VERSION,
        request_id: rec.request_id.as_deref(),
        route: rec.route,
        model: rec.model.as_deref(),
        stream: rec.stream,
        session_key,
        session_key_source,
        t_arrival: epoch_s(arrival),
        t_first_token: rec.first_token.map(epoch_s),
        t_end: epoch_s(end),
        end_reason: rec.end_reason().as_str(),
        // 499: the client left before a response head existed (the /metrics convention).
        http_status: rec.status.unwrap_or(499),
        prompt_tokens: rec.prompt_tokens,
        cached_tokens: rec.cached_tokens,
        generated_tokens,
        tool_calls,
        prompt_sha256: prompt.as_ref().map(|p| ids_sha256(&p.ids)),
    };
    serde_json::to_string(&line).unwrap_or_else(|err| {
        format!(
            "{{\"v\":{SCHEMA_VERSION},\"render_error\":{:?}}}",
            err.to_string()
        )
    })
}

struct Inner {
    sink: Arc<Sink>,
    rec: Mutex<Rec>,
    prompt: PromptSlot,
}

impl Drop for Inner {
    fn drop(&mut self) {
        let mut rec = std::mem::take(self.rec.get_mut().unwrap_or_else(|e| e.into_inner()));
        rec.dropped_at = Some(SystemTime::now());
        let prompt = self.prompt.take();
        self.sink.submit(rec, prompt);
    }
}

/// One request's shared record. Cloned into every observer; the line is emitted on the last drop.
#[derive(Clone)]
pub(crate) struct Entry(Arc<Inner>);

impl Entry {
    fn new(sink: Arc<Sink>, route: &'static str) -> Self {
        Self(Arc::new(Inner {
            sink,
            rec: Mutex::new(Rec {
                route,
                arrival: Some(SystemTime::now()),
                ..Rec::default()
            }),
            prompt: PromptSlot::default(),
        }))
    }

    fn with(&self, f: impl FnOnce(&mut Rec)) {
        f(&mut self.0.rec.lock().unwrap_or_else(|e| e.into_inner()));
    }

    /// A tool call the reply's parser emitted. Hashed later, on the writer thread.
    pub(crate) fn tool_call(&self, name: &str, arguments: &str) {
        self.with(|r| {
            r.tool_calls
                .get_or_insert_with(Vec::new)
                .push((name.to_owned(), arguments.to_owned()));
        });
    }
}

impl std::fmt::Debug for Entry {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("request_log::Entry")
    }
}

/// An event receiver's tie to its request's entry. The ORIGINAL receiver observes; a bridged
/// receiver only carries the entry for an explicit [`EndReason`] mark.
pub(crate) struct Link {
    entry: Entry,
    observe: bool,
    first_seen: bool,
    terminal: bool,
    tokens: u64,
}

impl Link {
    pub(crate) fn observer(entry: Entry) -> Self {
        Self {
            entry,
            observe: true,
            first_seen: false,
            terminal: false,
            tokens: 0,
        }
    }

    pub(crate) fn mark_only(&self) -> Self {
        Self {
            entry: self.entry.clone(),
            observe: false,
            first_seen: false,
            terminal: false,
            tokens: 0,
        }
    }

    pub(crate) fn observe(&mut self, event: &Event) {
        // Synthesized HTTP-side (the committed-stream prefill bridge), so it arrives on a
        // bridged receiver: any link records it.
        if let Event::DeadlineExceeded { .. } = event {
            self.terminal = true;
            self.mark(EndReason::Deadline);
            return;
        }
        if !self.observe {
            return;
        }
        match event {
            Event::Token { .. } => {
                if !self.first_seen {
                    self.first_seen = true;
                    let now = SystemTime::now();
                    self.entry.with(|r| {
                        r.first_token = Some(now);
                        r.reached_worker = true;
                    });
                }
                self.tokens += 1;
            }
            Event::PromptUsage { n_prompt, n_cached } => self.entry.with(|r| {
                r.reached_worker = true;
                r.prompt_tokens.get_or_insert(*n_prompt as u64);
                r.cached_tokens.get_or_insert(*n_cached as u64);
            }),
            Event::Done {
                stop_reason,
                n_tokens,
                n_prompt,
                n_cached,
                ..
            } => {
                self.terminal = true;
                let now = SystemTime::now();
                self.entry.with(|r| {
                    r.reached_worker = true;
                    r.stop_reason = Some(stop_reason.clone());
                    r.done_tokens = Some(*n_tokens as u64);
                    r.prompt_tokens = Some(*n_prompt as u64);
                    r.cached_tokens = Some(*n_cached as u64);
                    r.generation_end = Some(now);
                });
            }
            Event::Error(_) => {
                self.terminal = true;
                let now = SystemTime::now();
                self.entry.with(|r| {
                    r.engine_error = true;
                    r.generation_end = Some(now);
                });
            }
            Event::DeadlineExceeded { .. }
            | Event::PromptCapture { .. }
            | Event::TokenSnapshot(_) => {}
        }
    }

    /// The worker dropped its sender. Without a terminal event first, the stream failed.
    pub(crate) fn closed(&mut self) {
        if self.observe && !self.terminal {
            self.terminal = true;
            self.entry.with(|r| r.worker_closed = true);
        }
    }

    /// The consumer's own verdict (a deadline it enforced, a cancel it honored). First mark wins.
    pub(crate) fn mark(&self, reason: EndReason) {
        self.entry.with(|r| {
            r.mark.get_or_insert(reason);
        });
    }
}

impl Drop for Link {
    fn drop(&mut self) {
        if self.observe && self.tokens > 0 {
            let tokens = self.tokens;
            self.entry.with(|r| r.seen_tokens += tokens);
        }
    }
}

impl std::fmt::Debug for Link {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("request_log::Link")
            .field("observe", &self.observe)
            .finish()
    }
}

tokio::task_local! {
    static CURRENT: Entry;
}

fn current() -> Option<Entry> {
    CURRENT.try_with(Entry::clone).ok()
}

/// Called from `http_metrics::bind_model` with the canonical model name.
pub(crate) fn note_model(model: &str) {
    if let Some(entry) = current() {
        entry.with(|r| r.model = Some(model.to_owned()));
    }
}

/// Tie a request the handler is about to submit to its entry: the session identity, the prompt
/// slot on the worker-bound sender, the observer on the receiver and the tool parser. A no-op
/// when the log is not installed. `parses_tools` is false on the raw-text completions route.
pub(crate) fn bind(
    request: &mut crate::worker::Request,
    rx: &mut crate::worker::EventReceiver,
    parser: Option<&mut crate::toolcall::ToolStreamParser>,
    source: Option<SessionSource>,
    parses_tools: bool,
) {
    let Some(entry) = current() else {
        return;
    };
    let session = request.affinity.clone().zip(source);
    let request_id = request.request_id.clone();
    let model = request.model.clone();
    entry.with(|r| {
        r.session = session;
        r.request_id.get_or_insert(request_id);
        r.model.get_or_insert(model);
        if parses_tools {
            r.tool_calls.get_or_insert_with(Vec::new);
        }
    });
    request.tx.link_prompt(entry.0.prompt.clone());
    if let Some(parser) = parser {
        parser.link_request_log(entry.clone());
    }
    rx.link_observer(Link::observer(entry));
}

/// The four generation routes, by method and path.
fn logged_route(req: &Request) -> Option<&'static str> {
    if req.method() != axum::http::Method::POST {
        return None;
    }
    match req.uri().path() {
        "/v1/completions" => Some("/v1/completions"),
        "/v1/chat/completions" => Some("/v1/chat/completions"),
        "/v1/responses" => Some("/v1/responses"),
        "/v1/messages" => Some("/v1/messages"),
        _ => None,
    }
}

/// The request-log middleware, installed outermost on the router only when the log is set.
pub(crate) async fn observe(State(sink): State<Arc<Sink>>, req: Request, next: Next) -> Response {
    let Some(route) = logged_route(&req) else {
        return next.run(req).await;
    };
    let entry = Entry::new(sink, route);
    let response = CURRENT.scope(entry.clone(), next.run(req)).await;
    let headers = response.headers();
    let stream = headers
        .get(axum::http::header::CONTENT_TYPE)
        .and_then(|v| v.to_str().ok())
        .is_some_and(|v| v.starts_with("text/event-stream"));
    let request_id = headers
        .get("x-request-id")
        .or_else(|| headers.get("request-id"))
        .and_then(|v| v.to_str().ok())
        .map(str::to_owned);
    let status = response.status().as_u16();
    let now = SystemTime::now();
    entry.with(|r| {
        r.status = Some(status);
        r.stream = stream;
        if let Some(id) = request_id {
            r.request_id = Some(id);
        }
        if !stream {
            r.http_end = Some(now);
        }
    });
    if !stream {
        return response;
    }
    let (parts, body) = response.into_parts();
    Response::from_parts(
        parts,
        Body::new(LoggedBody {
            inner: Box::pin(body),
            entry: Some(entry),
        }),
    )
}

/// A streaming body that stamps the response end when it ends, fails or is dropped. Frames pass
/// through untouched; size hint and end-of-stream are the inner body's.
struct LoggedBody {
    inner: Pin<Box<Body>>,
    entry: Option<Entry>,
}

impl LoggedBody {
    fn end(&mut self) {
        if let Some(entry) = self.entry.take() {
            let now = SystemTime::now();
            entry.with(|r| r.http_end = Some(now));
        }
    }
}

impl Drop for LoggedBody {
    fn drop(&mut self) {
        self.end();
    }
}

impl HttpBody for LoggedBody {
    type Data = Bytes;
    type Error = axum::Error;

    fn poll_frame(
        mut self: Pin<&mut Self>,
        cx: &mut Context<'_>,
    ) -> Poll<Option<Result<Frame<Bytes>, axum::Error>>> {
        let next = self.inner.as_mut().poll_frame(cx);
        if matches!(&next, Poll::Ready(None) | Poll::Ready(Some(Err(_)))) {
            self.end();
        }
        next
    }

    fn is_end_stream(&self) -> bool {
        self.inner.is_end_stream()
    }

    fn size_hint(&self) -> SizeHint {
        self.inner.size_hint()
    }
}

static INSTALLED: OnceLock<Arc<Sink>> = OnceLock::new();

/// Boot: open the configured log. `Ok(None)` when the variable is unset or empty; an `Err` is a
/// startup FATAL (an operator who asked for a log and cannot get one must hear it at boot).
pub(crate) fn install_from_env() -> Result<Option<Arc<Sink>>, String> {
    let path = match std::env::var(ENV) {
        Ok(path) if path.is_empty() => return Ok(None),
        Ok(path) => path,
        Err(std::env::VarError::NotPresent) => return Ok(None),
        Err(std::env::VarError::NotUnicode(_)) => {
            return Err(format!("{ENV} must be valid UTF-8"));
        }
    };
    let sink = Sink::open(Path::new(&path)).map_err(|err| format!("{ENV}={path:?}: {err}"))?;
    let _ = INSTALLED.set(sink.clone());
    eprintln!(
        "[request-log] writing one line per generation request to {path} \
         (queue {QUEUE_LINES} lines / {} MiB, drops counted in memra_request_log_lines_total)",
        QUEUE_BYTES >> 20
    );
    Ok(Some(sink))
}

/// Shutdown: let the writer finish what it accepted, bounded.
pub(crate) fn drain_installed(timeout: Duration) {
    if let Some(sink) = INSTALLED.get()
        && !sink.drain(timeout)
    {
        eprintln!(
            "[request-log] WARN: writer still behind after {:.1}s at shutdown",
            timeout.as_secs_f64()
        );
    }
}

/// Prometheus rows for the installed log; empty when the log is not set.
pub(crate) fn render_metrics() -> String {
    let Some(sink) = INSTALLED.get() else {
        return String::new();
    };
    let c = &sink.counters;
    let mut out = String::new();
    crate::prometheus_header(
        &mut out,
        "memra_request_log_lines_total",
        "counter",
        "Request-log lines since process start by outcome: written, dropped because the queue \
         was full, or dropped because the write failed.",
    );
    for (outcome, value) in [
        ("written", c.written.load(Ordering::Relaxed)),
        (
            "dropped_queue_full",
            c.dropped_queue_full.load(Ordering::Relaxed),
        ),
        (
            "dropped_write_error",
            c.dropped_write_error.load(Ordering::Relaxed),
        ),
    ] {
        out.push_str(&format!(
            "memra_request_log_lines_total{{outcome=\"{outcome}\"}} {value}\n"
        ));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn rec(route: &'static str) -> Rec {
        Rec {
            route,
            arrival: Some(UNIX_EPOCH + Duration::from_micros(1_762_700_000_123_456)),
            ..Rec::default()
        }
    }

    #[test]
    fn end_reason_follows_the_terminal_signal_in_priority_order() {
        let mut r = rec("/v1/completions");
        r.status = Some(200);
        r.stop_reason = Some("Eos".into());
        assert_eq!(r.end_reason(), EndReason::Stop);
        r.stop_reason = Some("MaxNew".into());
        assert_eq!(r.end_reason(), EndReason::Length);
        r.stop_reason = Some("ContextFull".into());
        assert_eq!(r.end_reason(), EndReason::Length);
        // A consumer's own verdict outranks what the worker had sent.
        r.mark = Some(EndReason::Deadline);
        assert_eq!(r.end_reason(), EndReason::Deadline);

        let mut r = rec("/v1/completions");
        r.status = Some(200);
        r.engine_error = true;
        assert_eq!(r.end_reason(), EndReason::Error);
        let mut r = rec("/v1/completions");
        r.status = Some(200);
        r.worker_closed = true;
        assert_eq!(r.end_reason(), EndReason::Error);
        let mut r = rec("/v1/completions");
        r.status = Some(408);
        assert_eq!(r.end_reason(), EndReason::Deadline);
        r.status = Some(429);
        assert_eq!(r.end_reason(), EndReason::Error);
        r.status = None;
        assert_eq!(r.end_reason(), EndReason::Cancelled);
        r.status = Some(200);
        assert_eq!(r.end_reason(), EndReason::Cancelled);
    }

    #[test]
    fn line_hashes_identity_and_content_and_carries_no_text() {
        let mut r = rec("/v1/chat/completions");
        r.status = Some(200);
        r.session = Some(("my-session".into(), SessionSource::SessionId));
        r.tool_calls = Some(vec![("get_weather".into(), "{\"city\":\"Paris\"}".into())]);
        r.stop_reason = Some("Eos".into());
        r.done_tokens = Some(7);
        r.prompt_tokens = Some(40);
        r.cached_tokens = Some(32);
        r.http_end = Some(UNIX_EPOCH + Duration::from_micros(1_762_700_001_000_000));
        struct NoMarkers;
        impl ControlTokens for NoMarkers {
            fn is_control(&self, _: u32) -> bool {
                false
            }
        }
        let prompt = PromptTap {
            ids: vec![1, 2, 3],
            controls: Arc::new(NoMarkers),
        };
        let line: serde_json::Value = serde_json::from_str(&render(Pending {
            rec: r,
            prompt: Some(prompt),
            bytes: 0,
        }))
        .unwrap();
        assert_eq!(line["session_key"], sha256_hex(b"my-session"));
        assert_eq!(line["session_key_source"], "session_id");
        let mut le = Vec::new();
        for id in [1u32, 2, 3] {
            le.extend_from_slice(&id.to_le_bytes());
        }
        assert_eq!(line["prompt_sha256"], sha256_hex(&le));
        assert_eq!(line["tool_calls"][0]["name"], "get_weather");
        assert_eq!(
            line["tool_calls"][0]["arguments_sha256"],
            sha256_hex(b"{\"city\":\"Paris\"}")
        );
        assert_eq!(line["t_arrival"], 1_762_700_000.123_456);
        assert_eq!(line["t_end"], 1_762_700_001.0);
        assert_eq!(line["end_reason"], "stop");
        assert_eq!(line["generated_tokens"], 7);
        let text = line.to_string();
        assert!(
            !text.contains("my-session") && !text.contains("Paris"),
            "{text}"
        );
    }

    #[test]
    fn a_full_queue_drops_and_counts_instead_of_blocking() {
        // A sink whose writer never runs: the queue fills to its line bound, then drops.
        let (tx, _rx) = std::sync::mpsc::sync_channel(2);
        let sink = Sink {
            tx,
            counters: Arc::new(Counters {
                queued_bytes: AtomicUsize::new(0),
                accepted: AtomicU64::new(0),
                written: AtomicU64::new(0),
                dropped_queue_full: AtomicU64::new(0),
                dropped_write_error: AtomicU64::new(0),
                done: Mutex::new(0),
                done_cv: Condvar::new(),
            }),
        };
        let started = std::time::Instant::now();
        for _ in 0..5 {
            sink.submit(rec("/v1/completions"), None);
        }
        assert!(started.elapsed() < Duration::from_secs(1));
        assert_eq!(sink.counters.accepted.load(Ordering::Relaxed), 2);
        assert_eq!(sink.dropped(), 3);
        // The byte bound drops a line whose prompt copy alone exceeds it.
        let (tx, _rx2) = std::sync::mpsc::sync_channel(8);
        let sink = Sink {
            tx,
            counters: sink.counters.clone(),
        };
        struct NoMarkers;
        impl ControlTokens for NoMarkers {
            fn is_control(&self, _: u32) -> bool {
                false
            }
        }
        sink.submit(
            rec("/v1/completions"),
            Some(PromptTap {
                ids: vec![0; QUEUE_BYTES / 4 + 1],
                controls: Arc::new(NoMarkers),
            }),
        );
        assert_eq!(sink.dropped(), 4);
    }
}
