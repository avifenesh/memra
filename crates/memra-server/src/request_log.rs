//! Per-request timing log (`MEMRA_REQUEST_LOG=<path>`): one JSON line per generation request on
//! `/v1/completions`, `/v1/chat/completions`, `/v1/responses` and `/v1/messages`, streaming and
//! blocking, written by a dedicated thread.
//!
//! WHAT IT IS FOR. Arrival, first token and end times, the token counts, the tool calls in the
//! reply and a session key that is stable across a session's turns are what a model needs to
//! predict when a session's next request arrives. The log carries no prompt or reply text:
//! content appears only as sha256 digests, so the file is safe to keep. The field contract is
//! `docs/SERVING.md` "Per-request timing log".
//!
//! CONFIG, NOT A DOOR. With the variable unset the middleware is not installed, no request
//! carries a link, and each hook below is one `None` check. The log observes; no hook changes an
//! event, a parsed piece or a response frame, so generated bytes are the same with it on or off
//! (`request_log_on_and_off_serve_identical_bytes`, plus the device A/B in the PR receipt).
//!
//! ONE SOURCE PER FIELD:
//!   * arrival, HTTP status, request id, end of the response body: [`observe`], the outermost
//!     layer on the generation routes.
//!   * session identity and model: the handler, where it builds the worker request ([`bind`]).
//!   * the prompt token ids: the worker, after it tokenizes ([`PromptSlot`]). One copy per
//!     request; the digest and the fingerprint key are computed on the writer thread.
//!   * first token, prompt/cached/generated counts, stop reason, engine error: the request's
//!     ORIGINAL event receiver ([`Link`]), which receives each worker event exactly once.
//!     Receivers bridged off it (the admission and first-token peeks) carry a mark-only link.
//!   * tool calls: the request's tool parser, as it emits them.
//!
//! The line is emitted when the last holder of the request's [`Entry`] drops: the response body
//! and every receiver and parser of the request. A background request's line therefore waits for
//! its generation, not for the response that queued it.
//!
//! OFF THE HOT PATH. The GPU worker does one copy of the prompt ids per request, and only when
//! the log is set. Per received token event the cost is one branch and one integer add: no lock,
//! allocation or I/O. Hashing and serialization run on the writer thread. The queue in between
//! is bounded in lines and bytes; a line that does not fit is dropped and counted
//! (`memra_request_log_lines_total`), never waited for.

